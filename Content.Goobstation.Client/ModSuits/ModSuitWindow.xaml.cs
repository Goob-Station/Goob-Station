using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Goobstation.Shared.ModSuits;
using Content.Goobstation.Shared.ModSuits.Components;
using Content.Goobstation.Shared.ModSuits.Systems;
using Content.Shared.Power.EntitySystems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Goobstation.Client.ModSuits;

[GenerateTypedNameReferences]
public sealed partial class ModSuitWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly ModSuitSystem _modSuit;
    private readonly SharedBatterySystem _battery;

    private EntityUid _suit;
    private TimeSpan _chargeAccumulator;
    private readonly Dictionary<string, Button> _partButtons = new();
    private readonly Dictionary<EntityUid, ModuleRow> _moduleRows = new();
    private bool _modulesBuilt;

    public event Action? OnActivate;
    public event Action? OnToggleAllParts;
    public event Action<string>? OnTogglePart;
    public event Action<NetEntity>? OnModuleToggle;
    public event Action<NetEntity>? OnModulePin;
    public event Action<NetEntity>? OnModuleRemove;

    public ModSuitWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _modSuit = _entMan.System<ModSuitSystem>();
        _battery = _entMan.System<SharedBatterySystem>();

        ActivateButton.OnPressed += _ => OnActivate?.Invoke();
        ToggleAllButton.OnPressed += _ => OnToggleAllParts?.Invoke();
    }

    public void SetSuit(EntityUid suit)
    {
        _suit = suit;
        Refresh();
    }

    public void Refresh()
    {
        if (!_entMan.TryGetComponent<ModSuitComponent>(_suit, out var suit))
            return;

        var ent = (_suit, suit);
        var theme = _proto.Index(suit.Theme);

        var state = suit.State;
        StatusLabel.Text = Loc.GetString("modsuit-ui-status", ("state", Loc.GetString($"modsuit-ui-state-{state.ToString().ToLowerInvariant()}")));
        ComplexityLabel.Text = Loc.GetString("modsuit-ui-complexity", ("current", _modSuit.GetComplexity(ent)), ("max", theme.ComplexityMax));
        ActivateButton.Text = Loc.GetString(suit.State is ModSuitState.Inactive or ModSuitState.Deactivating
            ? "modsuit-ui-activate"
            : "modsuit-ui-deactivate");
        ActivateButton.Disabled = suit.State is ModSuitState.Activating or ModSuitState.Deactivating;
        ToggleAllButton.Disabled = suit.State != ModSuitState.Inactive || suit.DeployQueue.Count > 0;

        UpdateCharge(ent);
        RebuildParts(ent);
        RebuildModules(ent);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _chargeAccumulator += TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_chargeAccumulator < TimeSpan.FromSeconds(0.5))
            return;

        _chargeAccumulator = TimeSpan.Zero;
        if (_entMan.TryGetComponent<ModSuitComponent>(_suit, out var suit))
            UpdateCharge((_suit, suit));
    }

    private void UpdateCharge(Entity<ModSuitComponent> suit)
    {
        CoreLabel.Text = _modSuit.GetCore(suit) is { } core
            ? Loc.GetString("modsuit-ui-core", ("core", _entMan.GetComponent<MetaDataComponent>(core).EntityName))
            : Loc.GetString("modsuit-ui-core-none");

        if (_modSuit.GetBattery(suit) is not { } battery)
        {
            ChargeLabel.Text = Loc.GetString("modsuit-ui-no-core");
            return;
        }

        var percent = (int) MathF.Round(_battery.GetChargeLevel(battery.AsNullable()) * 100f);
        ChargeLabel.Text = Loc.GetString("modsuit-ui-charge",
            ("percent", percent),
            ("drain", _modSuit.GetTotalDrain(suit).ToString("0.##")));
    }

    private void RebuildParts(Entity<ModSuitComponent> suit)
    {
        var slots = suit.Comp.PartEntities.Keys.ToList();
        if (!slots.SequenceEqual(_partButtons.Keys))
        {
            PartsGrid.RemoveAllChildren();
            _partButtons.Clear();

            foreach (var slot in slots)
            {
                var button = new Button
                {
                    Text = Loc.GetString($"modsuit-ui-part-{slot.ToLowerInvariant()}"),
                    HorizontalExpand = true,
                    ClipText = true,
                    ToggleMode = true,
                };

                var partSlot = slot;
                button.OnPressed += _ => OnTogglePart?.Invoke(partSlot);
                PartsGrid.AddChild(button);
                _partButtons[slot] = button;
            }
        }

        foreach (var (slot, button) in _partButtons)
        {
            button.Disabled = suit.Comp.State != ModSuitState.Inactive || suit.Comp.DeployQueue.Count > 0;
            button.Pressed = _modSuit.IsPartDeployed(suit, slot);
        }
    }

    private void RebuildModules(Entity<ModSuitComponent> suit)
    {
        var modules = suit.Comp.ModulesContainer.ContainedEntities.ToList();
        if (!_modulesBuilt || !modules.SequenceEqual(_moduleRows.Keys))
        {
            _modulesBuilt = true;
            ModulesList.RemoveAllChildren();
            _moduleRows.Clear();

            if (modules.Count == 0)
            {
                ModulesList.AddChild(new Label
                {
                    Text = Loc.GetString("modsuit-ui-no-modules"),
                    FontColorOverride = Color.Gray,
                });
            }

            foreach (var module in modules)
            {
                if (!_entMan.TryGetComponent<ModModuleComponent>(module, out var moduleComp))
                    continue;

                var row = BuildModuleRow((module, moduleComp));
                ModulesList.AddChild(row.Root);
                _moduleRows[module] = row;
            }
        }

        foreach (var (module, row) in _moduleRows)
        {
            if (_entMan.TryGetComponent<ModModuleComponent>(module, out var moduleComp))
                UpdateModuleRow(row, moduleComp);
        }
    }

    private void UpdateModuleRow(ModuleRow row, ModModuleComponent module)
    {
        if (row.Use is { } use)
        {
            use.Pressed = module.Active;
            use.Text = Loc.GetString(module.Type == ModModuleType.Usable
                ? "modsuit-ui-module-use"
                : module.Active ? "modsuit-ui-module-off" : "modsuit-ui-module-on");
        }

        if (row.Pin is { } pin)
            pin.Text = Loc.GetString(module.Pinned ? "modsuit-ui-module-unpin" : "modsuit-ui-module-pin");
    }

    private ModuleRow BuildModuleRow(Entity<ModModuleComponent> module)
    {
        var netModule = _entMan.GetNetEntity(module);
        var type = module.Comp.Type;
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        var icon = new SpriteView
        {
            SetSize = new Vector2(32, 32),
            OverrideDirection = Direction.South,
            VerticalAlignment = VAlignment.Center,
        };
        icon.SetEntity(module);
        row.AddChild(icon);

        var info = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        info.AddChild(new Label
        {
            Text = _entMan.GetComponent<MetaDataComponent>(module).EntityName,
            ClipText = true,
        });
        info.AddChild(new Label
        {
            Text = Loc.GetString("modsuit-ui-module-info",
                ("type", Loc.GetString($"modsuit-ui-module-type-{type.ToString().ToLowerInvariant()}")),
                ("complexity", module.Comp.Complexity),
                ("power", (module.Comp.IdlePower + module.Comp.ActivePower).ToString("0.##"))),
            FontColorOverride = Color.Gray,
            ClipText = true,
        });
        row.AddChild(info);

        Button? useButton = null;
        Button? pinButton = null;
        if (type != ModModuleType.Passive)
        {
            useButton = new Button
            {
                ToggleMode = type != ModModuleType.Usable,
                MinWidth = 50,
            };
            useButton.OnPressed += _ => OnModuleToggle?.Invoke(netModule);
            row.AddChild(useButton);

            pinButton = new Button { MinWidth = 50 };
            pinButton.OnPressed += _ => OnModulePin?.Invoke(netModule);
            row.AddChild(pinButton);
        }

        if (!module.Comp.Removable)
        {
            row.AddChild(new Label
            {
                Text = Loc.GetString("modsuit-ui-module-builtin"),
                FontColorOverride = Color.Gray,
                VerticalAlignment = VAlignment.Center,
            });
        }
        else
        {
            var remove = new Button
            {
                Text = Loc.GetString("modsuit-ui-module-remove"),
                MinWidth = 50,
            };
            remove.OnPressed += _ => OnModuleRemove?.Invoke(netModule);
            row.AddChild(remove);
        }

        return new ModuleRow(row, useButton, pinButton);
    }

    private sealed record ModuleRow(Control Root, Button? Use, Button? Pin);
}
