using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.News.UI;

[GenerateTypedNameReferences]
public sealed partial class NewsReaderWindow : BaseWindow
{
    [Dependency] private NewsManager _news = default!;

    private const float ResizeMargin = 7;

    public event Action? NeverPressed;

    public NewsEntryPrototype? Entry { get; private set; }

    public NewsReaderWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DismissButton.OnPressed += _ => Close();
        NeverButton.OnPressed += _ =>
        {
            NeverPressed?.Invoke();
            Close();
        };
    }

    public void SetEntry(NewsEntryPrototype entry, bool popup)
    {
        Entry = entry;
        TitleLabel.Text = Loc.GetString(entry.Title);

        DateLabel.Visible = entry.Date != null;
        if (entry.Date is { } date)
            DateLabel.Text = NewsManager.FormatDate(date);

        NeverButton.Visible = popup && entry.Popup?.AllowNeverShow == true;
        DismissButton.Text = Loc.GetString(popup ? "news-reader-later" : "news-reader-close");

        DocumentContainer.RemoveAllChildren();
        _news.TryRender(DocumentContainer, entry.Document);
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.Move;

        if (relativeMousePos.Y < ResizeMargin)
            mode = DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - ResizeMargin)
            mode = DragMode.Bottom;

        if (relativeMousePos.X < ResizeMargin)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - ResizeMargin)
            mode |= DragMode.Right;

        return mode;
    }
}
