using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.News.UI;

[GenerateTypedNameReferences]
public sealed partial class NewsFeed : BoxContainer
{
    [Dependency] private NewsManager _news = default!;

    public NewsFeed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _news.Changed += Rebuild;
        Rebuild();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _news.Changed -= Rebuild;
    }

    private void Rebuild()
    {
        Entries.RemoveAllChildren();

        foreach (var entry in _news.Pinned)
        {
            Entries.AddChild(new NewsPinnedCard(entry));
        }

        foreach (var entry in _news.Posts)
        {
            Entries.AddChild(new NewsPostItem(entry, _news.IsUnread(entry)));
        }

        EmptyLabel.Visible = Entries.ChildCount == 0;
    }
}
