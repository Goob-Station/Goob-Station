using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.News.UI;

[GenerateTypedNameReferences]
public sealed partial class NewsPostItem : BoxContainer
{
    private static readonly Color SummaryColor = Color.FromHex("#9aa1a8");

    public NewsPostItem(NewsEntryPrototype entry, bool unread)
    {
        RobustXamlLoader.Load(this);

        DateLabel.Text = entry.Date is { } date ? NewsManager.FormatDate(date) : string.Empty;
        TitleLabel.Text = Loc.GetString(entry.Title);
        NewLabel.Visible = unread;

        if (entry.Summary is { } summary)
            SummaryContainer.AddChild(CreateSummary(summary));

        ReadMoreButton.OnPressed += _ => UserInterfaceManager.GetUIController<NewsUIController>().Open(entry.ID);
    }

    public static RichTextLabel CreateSummary(LocId summary)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        var message = new FormattedMessage();
        message.PushColor(SummaryColor);
        message.AddMarkupPermissive(Loc.GetString(summary));
        message.Pop();
        label.SetMessage(message);
        return label;
    }
}
