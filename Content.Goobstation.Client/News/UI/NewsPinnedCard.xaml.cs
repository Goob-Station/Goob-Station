using Content.Goobstation.UIKit.UserInterface.Lobby;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.News.UI;

[GenerateTypedNameReferences]
public sealed partial class NewsPinnedCard : PanelContainer
{
    [Dependency] private NewsManager _news = default!;

    public NewsPinnedCard(NewsEntryPrototype entry)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TitleLabel.Text = Loc.GetString("news-pinned-title", ("title", Loc.GetString(entry.Title)));

        if (entry.Card is { } card)
        {
            _news.TryRender(Body, card);
            return;
        }

        if (entry.Summary is { } summary)
            Body.AddChild(NewsPostItem.CreateSummary(summary));

        var readMore = new Button
        {
            Text = Loc.GetString("news-read-more"),
            StyleClasses = { HullStyleClasses.Plate },
            HorizontalAlignment = HAlignment.Left,
        };
        readMore.OnPressed += _ => UserInterfaceManager.GetUIController<NewsUIController>().Open(entry.ID);
        Body.AddChild(readMore);
    }
}
