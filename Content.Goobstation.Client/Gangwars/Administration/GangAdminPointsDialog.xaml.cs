using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.Gangwars.Administration;

/// <summary>
/// Prompt to change someones total points.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GangAdminPointsDialog : DefaultWindow
{
    public event Action<int>? OnConfirmed;

    public GangAdminPointsDialog(string memberName, int currentPoints)
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString("gang-admin-points-title", ("name", memberName));

        PointsEdit.Text = currentPoints.ToString();
        PointsEdit.OnTextEntered += _ => Confirm();
        ConfirmButton.OnPressed += _ => Confirm();
    }

    private void Confirm()
    {
        if (!int.TryParse(PointsEdit.Text, out var points))
            return;

        OnConfirmed?.Invoke(points);
        Close();
    }
}
