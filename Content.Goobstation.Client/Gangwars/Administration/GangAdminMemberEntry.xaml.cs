using Content.Goobstation.Shared.Gangwars.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.Gangwars.Administration;

/// <summary>
/// Gang member listings.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GangAdminMemberEntry : BoxContainer
{
    public event Action? OnSelected;
    public event Action? OnPointsPressed;

    public GangAdminMemberEntry(GangAdminMemberInfo member, bool selected)
    {
        RobustXamlLoader.Load(this);

        NameButton.Text = member.IsLeader
            ? Loc.GetString("gang-admin-member-leader", ("name", member.Name))
            : member.Name;
        NameButton.Pressed = selected;
        NameButton.OnPressed += _ => OnSelected?.Invoke();

        PointsButton.Text = Loc.GetString("gang-admin-points-button", ("points", member.Points));
        PointsButton.OnPressed += _ => OnPointsPressed?.Invoke();
    }
}
