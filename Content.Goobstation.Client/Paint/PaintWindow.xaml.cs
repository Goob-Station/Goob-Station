using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Goobstation.Shared.Paint;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.Paint;

public enum PaintWindowTool : byte
{
    Brush,
    Eraser,
    Line,
    Rectangle,
    Ellipse,
    Picker,
}

[GenerateTypedNameReferences]
public sealed partial class PaintWindow : FancyWindow
{
    private const string IconDirectory = "/Textures/_Goobstation/Interface/Paint/";

    private static readonly (PaintWindowTool Tool, string Icon, string Tooltip)[] Tools =
    {
        (PaintWindowTool.Brush, "brush", "paint-tool-brush"),
        (PaintWindowTool.Eraser, "eraser", "paint-tool-eraser"),
        (PaintWindowTool.Line, "line", "paint-tool-line"),
        (PaintWindowTool.Rectangle, "rectangle", "paint-tool-rectangle"),
        (PaintWindowTool.Ellipse, "ellipse", "paint-tool-ellipse"),
        (PaintWindowTool.Picker, "picker", "paint-tool-picker"),
    };

    private static readonly (PaintBrushStyle Style, string Icon, string Tooltip)[] Styles =
    {
        (PaintBrushStyle.Round, "style-round", "paint-style-round"),
        (PaintBrushStyle.Square, "style-square", "paint-style-square"),
        (PaintBrushStyle.Spray, "style-spray", "paint-style-spray"),
        (PaintBrushStyle.Calligraphy, "style-calligraphy", "paint-style-calligraphy"),
    };

    public event Action? FrameUpdated;
    public event Action? UndoPressed;
    public event Action<string>? FinishPressed;

    public PaintWindowTool SelectedTool { get; private set; } = PaintWindowTool.Brush;
    public PaintBrushStyle SelectedStyle { get; private set; } = PaintBrushStyle.Round;
    public int BrushSize => (int) MathF.Round(SizeSlider.Value);
    public bool HasTool { get; private set; }

    public Color PickedColor
    {
        get => ColorPicker.Color;
        set
        {
            ColorPicker.Color = value;
            UpdateSwatch();
        }
    }

    private readonly Dictionary<PaintWindowTool, Button> _toolButtons = new();
    private readonly Dictionary<PaintBrushStyle, Button> _styleButtons = new();
    private readonly StyleBoxFlat _swatch = new();
    private Color _toolColor = Color.Black;
    private bool _finished;

    public PaintWindow()
    {
        RobustXamlLoader.Load(this);

        var toolGroup = new ButtonGroup();
        foreach (var (tool, icon, tooltip) in Tools)
        {
            var button = CreateIconButton(icon, tooltip, toolGroup);
            button.OnPressed += _ => SelectTool(tool);
            _toolButtons[tool] = button;
            ToolButtons.AddChild(button);
        }

        var styleGroup = new ButtonGroup();
        foreach (var (style, icon, tooltip) in Styles)
        {
            var button = CreateIconButton(icon, tooltip, styleGroup);
            button.OnPressed += _ => SelectStyle(style);
            _styleButtons[style] = button;
            StyleButtons.AddChild(button);
        }

        _toolButtons[SelectedTool].Pressed = true;
        _styleButtons[SelectedStyle].Pressed = true;

        SizeSlider.OnValueChanged += _ => UpdateSize();
        ColorPicker.IsAlphaVisible = false;
        ColorPicker.Color = Color.Black;
        ColorPicker.OnColorChanged += _ => UpdateSwatch();
        ColorSwatch.PanelOverride = _swatch;

        UndoButton.OnPressed += _ => UndoPressed?.Invoke();
        FinishButton.OnPressed += _ => FinishPressed?.Invoke(TitleEdit.Text);
        TitleEdit.IsValid = text => text.Length <= PaintFinishMessage.MaxTitleLength;

        UpdateSize();
        SetTool(null, false, Color.Black);
    }

    public void SetFinished(bool finished, string? title, string? artist)
    {
        _finished = finished;
        EditPanel.Visible = !finished;
        FinishedLabel.Visible = finished;
        Canvas.Interactive = HasTool && !finished;

        if (!finished)
            return;

        Canvas.EndStroke();
        FinishedLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("paint-window-finished",
            ("title", FormattedMessage.EscapeText(title ?? Loc.GetString("paint-untitled"))),
            ("artist", FormattedMessage.EscapeText(artist ?? Loc.GetString("paint-unknown-artist"))))));
        StatusLabel.Text = string.Empty;
    }

    private static Button CreateIconButton(string icon, string tooltip, ButtonGroup group)
    {
        var button = new Button
        {
            ToggleMode = true,
            Group = group,
            ToolTip = Loc.GetString(tooltip),
            MinSize = new Vector2(38, 34),
        };

        button.AddChild(new TextureRect
        {
            TexturePath = IconDirectory + icon + ".svg.192dpi.png",
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            SetSize = new Vector2(22, 22),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        });

        return button;
    }

    public void SetTool(PaintToolComponent? tool, bool picker, Color toolColor)
    {
        HasTool = tool != null;
        _toolColor = toolColor;
        ColorPicker.Visible = picker;
        ColorSwatch.Visible = HasTool;
        Canvas.Interactive = HasTool && !_finished;
        UndoButton.Disabled = !HasTool;
        FinishButton.Disabled = !HasTool;

        foreach (var button in _toolButtons.Values)
        {
            button.Disabled = !HasTool;
        }

        foreach (var button in _styleButtons.Values)
        {
            button.Disabled = !HasTool;
        }

        if (tool == null)
        {
            Canvas.EndStroke();
            StatusLabel.Text = _finished ? string.Empty : Loc.GetString("paint-window-no-tool");
            return;
        }

        _toolButtons[PaintWindowTool.Eraser].Disabled = !tool.CanErase;
        _toolButtons[PaintWindowTool.Picker].Disabled = !picker;
        if (_toolButtons[SelectedTool].Disabled)
        {
            _toolButtons[PaintWindowTool.Brush].Pressed = true;
            SelectTool(PaintWindowTool.Brush);
        }

        var min = Math.Max(1, tool.MinBrushSize);
        var max = Math.Max(min, tool.MaxBrushSize);
        SizeSlider.MinValue = min;
        SizeSlider.MaxValue = max;
        SizeSlider.Value = Math.Clamp(SizeSlider.Value, min, max);

        StatusLabel.Text = string.Empty;
        UpdateSize();
        UpdateSwatch();
    }

    private void SelectTool(PaintWindowTool tool)
    {
        SelectedTool = tool;
        UpdateSize();
    }

    private void SelectStyle(PaintBrushStyle style)
    {
        SelectedStyle = style;
        UpdateSize();
    }

    private void UpdateSize()
    {
        SizeLabel.Text = Loc.GetString("paint-window-size-value", ("size", BrushSize));
        var picker = SelectedTool == PaintWindowTool.Picker;
        Canvas.SetBrush(picker ? 1 : BrushSize, picker ? PaintBrushStyle.Square : SelectedStyle);
    }

    private void UpdateSwatch()
    {
        _swatch.BackgroundColor = ColorPicker.Visible ? ColorPicker.Color : _toolColor;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        FrameUpdated?.Invoke();
    }
}
