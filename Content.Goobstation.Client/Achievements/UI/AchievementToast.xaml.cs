using System.Text;
using Content.Goobstation.Shared.Achievements;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Goobstation.Client.Achievements.UI;

[GenerateTypedNameReferences]
public sealed partial class AchievementToast : PanelContainer
{
    private const int MaxLineLength = 48;

    public TimeSpan ExpireTime;

    public AchievementToast(AchievementData data, SpriteSystem sprite, TimeSpan expireTime)
    {
        RobustXamlLoader.Load(this);

        ExpireTime = expireTime;

        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1B1B1E").WithAlpha(0.95f),
            BorderColor = Color.FromHex("#C9A13B"),
            BorderThickness = new Thickness(2),
        };

        if (data.Icon is { } icon)
            Icon.Texture = sprite.Frame0(icon);

        if (data.Name is { } name)
            NameLabel.Text = Loc.GetString(name);

        if (data.Description is { } description)
            AddDescription(Loc.GetString(description));
    }

    private void AddDescription(string text)
    {
        var line = new StringBuilder();
        foreach (var word in text.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length > 0 && line.Length + word.Length + 1 > MaxLineLength)
            {
                AddLine(line.ToString());
                line.Clear();
            }

            if (line.Length > 0)
                line.Append(' ');

            line.Append(word);
        }

        if (line.Length > 0)
            AddLine(line.ToString());
    }

    private void AddLine(string text)
    {
        DescriptionBox.AddChild(new Label
        {
            Text = text,
            Align = Label.AlignMode.Center,
            HorizontalAlignment = HAlignment.Center,
            StyleClasses = { "LabelWeak" },
            MouseFilter = MouseFilterMode.Ignore,
        });
    }
}
