using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Goobstation.Maths.FixedPoint;
using Content.Goobstation.UIKit.UserInterface.Controls.NodeTree;
using Content.Shared.Actions.Components;
using Content.Shared.Store;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.Store.UI;

[GenerateTypedNameReferences]
public sealed partial class StoreTreeMenu : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private static readonly Color LockedEdgeColor = Color.FromHex("#3c3c46");

    private readonly SpriteSystem _sprite;

    public event Action<ProtoId<ListingPrototype>>? OnBuy;

    private readonly Dictionary<ProtoId<ListingPrototype>, NodeTreeButton> _nodes = new();
    private readonly List<(NodeTreeEdge Edge, ProtoId<ListingPrototype> Parent, ProtoId<ListingPrototype> Child)> _edges = new();
    private readonly Dictionary<ProtoId<ListingPrototype>, ListingDataWithCostModifiers> _available = new();
    private HashSet<ProtoId<ListingPrototype>> _purchased = new();
    private Dictionary<ProtoId<CurrencyPrototype>, FixedPoint2> _balance = new();
    private ProtoId<StoreTreePrototype>? _tree;
    private ProtoId<ListingPrototype>? _selected;

    public StoreTreeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();

        RecenterButton.OnPressed += _ => Tree.Recenter();
        BuyButton.OnPressed += _ =>
        {
            if (_selected is { } id)
                OnBuy?.Invoke(id);
        };
    }

    public void UpdateState(StoreTreeUpdateState state, bool rebuild = false)
    {
        _purchased = state.Purchased;
        _balance = state.Balance;
        _available.Clear();
        foreach (var listing in state.Listings)
        {
            _available[listing.ID] = listing;
        }

        if (rebuild || _tree != state.Tree)
            BuildTree(state.Tree);

        UpdateBalance();

        foreach (var (id, node) in _nodes)
        {
            node.State = GetState(id);
        }

        foreach (var (edge, parent, child) in _edges)
        {
            edge.Color = GetEdgeColor(GetState(parent), GetState(child));
        }

        UpdateInfo();
    }

    private void BuildTree(ProtoId<StoreTreePrototype> treeId)
    {
        _tree = treeId;
        Tree.Clear();
        _nodes.Clear();
        _edges.Clear();

        if (!_proto.TryIndex(treeId, out var tree))
            return;

        Title = Loc.GetString(tree.Name);
        Tree.Home = tree.Home;

        foreach (var label in tree.Labels)
        {
            var control = new Label
            {
                Text = Loc.GetString(label.Text),
                FontColorOverride = label.Color,
            };
            control.AddStyleClass(StyleClass.LabelHeading);
            Tree.AddDecoration(control, label.Position);
        }

        foreach (var (id, node) in tree.Nodes)
        {
            if (!_proto.TryIndex(id, out var listing))
                continue;

            var button = new NodeTreeButton
            {
                ToolTip = ListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _proto),
            };
            button.Icon.Texture = GetIcon(listing);
            button.OnPressed += _ => Select(id);
            Tree.AddNode(button, node.Position);
            _nodes[id] = button;
        }

        foreach (var (id, node) in tree.Nodes)
        {
            if (!_nodes.TryGetValue(id, out var child))
                continue;

            foreach (var parentId in node.Parents)
            {
                if (_nodes.TryGetValue(parentId, out var parent))
                    _edges.Add((Tree.AddEdge(parent, child), parentId, id));
            }
        }

        if (_selected is { } selected)
        {
            if (_nodes.TryGetValue(selected, out var selectedNode))
                selectedNode.Selected = true;
            else
                _selected = null;
        }

        Tree.Recenter();
    }

    private NodeTreeState GetState(ProtoId<ListingPrototype> id)
    {
        if (_available.TryGetValue(id, out var listing))
            return listing.CanBuyWith(_balance) ? NodeTreeState.Available : NodeTreeState.Unaffordable;

        return _purchased.Contains(id) ? NodeTreeState.Unlocked : NodeTreeState.Locked;
    }

    private static Color GetEdgeColor(NodeTreeState parent, NodeTreeState child)
    {
        if (parent != NodeTreeState.Unlocked)
            return LockedEdgeColor;

        return child == NodeTreeState.Unlocked
            ? NodeTreeButton.GetColors(NodeTreeState.Unlocked).Border
            : Color.White;
    }

    private void Select(ProtoId<ListingPrototype> id)
    {
        if (_selected is { } previous && _nodes.TryGetValue(previous, out var previousNode))
            previousNode.Selected = false;

        _selected = id;
        if (_nodes.TryGetValue(id, out var node))
            node.Selected = true;

        UpdateInfo();
    }

    private void UpdateBalance()
    {
        var lines = new List<string>();
        foreach (var (currencyId, amount) in _balance)
        {
            if (!_proto.TryIndex(currencyId, out var currency))
                continue;

            lines.Add(Loc.GetString("store-ui-balance-display",
                ("amount", amount),
                ("currency", Loc.GetString(currency.DisplayName, ("amount", 1)))));
        }

        BalanceLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Join("\n", lines)));
    }

    private void UpdateInfo()
    {
        if (_selected is not { } id || !_proto.TryIndex(id, out var proto))
        {
            InfoPanel.Visible = false;
            NoSelectionLabel.Visible = true;
            return;
        }

        InfoPanel.Visible = true;
        NoSelectionLabel.Visible = false;

        var state = GetState(id);

        InfoIcon.Texture = GetIcon(proto);
        InfoName.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("store-tree-listing-name", ("name", ListingLocalisationHelpers.GetLocalisedNameOrEntityName(proto, _proto)))));
        InfoCategory.Text = string.Join(", ", proto.Categories
            .Select(c => _proto.TryIndex(c, out var category) ? Loc.GetString(category.Name) : null)
            .OfType<string>());
        InfoDescription.SetMessage(FormattedMessage.FromMarkupPermissive(
            ListingLocalisationHelpers.GetLocalisedDescriptionOrEntityDescription(proto, _proto)));

        IReadOnlyDictionary<ProtoId<CurrencyPrototype>, FixedPoint2> cost = _available.TryGetValue(id, out var available)
            ? available.Cost
            : proto.Cost;
        InfoCost.SetMessage(FormattedMessage.FromMarkupPermissive(
            Loc.GetString("store-tree-cost", ("cost", FormatCost(cost)))));

        var (_, _, stateColor) = NodeTreeButton.GetColors(state);
        InfoStatus.SetMessage(Loc.GetString(state switch
        {
            NodeTreeState.Unlocked => "store-tree-state-unlocked",
            NodeTreeState.Available => "store-tree-state-available",
            NodeTreeState.Unaffordable => "store-tree-state-unaffordable",
            _ => "store-tree-state-locked",
        }), stateColor);

        BuyButton.Disabled = state != NodeTreeState.Available;
        BuyButton.Text = Loc.GetString(state == NodeTreeState.Unlocked ? "store-tree-purchased-button" : "store-tree-buy-button");
    }

    private string FormatCost(IReadOnlyDictionary<ProtoId<CurrencyPrototype>, FixedPoint2> cost)
    {
        if (cost.Count == 0)
            return Loc.GetString("store-currency-free");

        var parts = new List<string>();
        foreach (var (currencyId, amount) in cost)
        {
            if (!_proto.TryIndex(currencyId, out var currency))
                continue;

            parts.Add(Loc.GetString("store-ui-price-display",
                ("amount", amount),
                ("currency", Loc.GetString(currency.DisplayName, ("amount", amount)))));
        }

        return string.Join(", ", parts);
    }

    private Texture? GetIcon(ListingPrototype listing)
    {
        if (listing.Icon != null)
            return _sprite.Frame0(listing.Icon);

        if (listing.ProductEntity is { } entity)
            return _sprite.GetPrototypeIcon(entity).Default;

        if (listing.ProductAction is { } actionId &&
            _proto.TryIndex(actionId, out var actionProto) &&
            actionProto.TryGetComponent<ActionComponent>(out var action, _entMan.ComponentFactory) &&
            action.Icon != null)
            return _sprite.Frame0(action.Icon);

        return null;
    }
}
