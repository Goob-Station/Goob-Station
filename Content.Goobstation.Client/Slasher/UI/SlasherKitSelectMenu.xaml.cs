using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Systems.Guidebook;
using Content.Goobstation.Client.Slasher.UI.VideoStore;
using Content.Goobstation.Shared.Slasher.UI;
using Content.Shared.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Goobstation.Client.Slasher.UI;

[GenerateTypedNameReferences]
public sealed partial class SlasherKitSelectMenu : BaseWindow
{
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;
    public event Action<string>? OnKitSelected;
    private readonly SpriteSystem _sprites;
    private List<SlasherKitInfo> _kits = new();

    public SlasherKitSelectMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprites = _sysMan.GetEntitySystem<SpriteSystem>();

        Rack.SetSign(
            Loc.GetString("slasher-kit-store-sign"),
            StorePalette.Pink,
            Loc.GetString("slasher-kit-store-sign-accent"),
            StorePalette.Cyan);
        Rack.OnSelected += OnRackSelected;
        Layers.OnJump += GoTo;
        LeftArrow.OnPressed += _ => Rack.Move(-1);
        RightArrow.OnPressed += _ => Rack.Move(1);
        Card.OnRent += id => OnKitSelected?.Invoke(id);
        Card.OnGuide += OpenGuide;
        Card.OnSequels += () => GoTo(Rack.ActiveTier + 1);
        Card.OnPrequel += () => GoTo(Rack.ActiveTier - 1);

        LayoutContainer.SetPosition(Rack, new Vector2(100f, 40f));
        LayoutContainer.SetPosition(Layers, new Vector2(16f, 26f));
        LayoutContainer.SetPosition(LeftArrow, new Vector2(380f, 616f));
        LayoutContainer.SetPosition(RightArrow, new Vector2(550f, 616f));
        LayoutContainer.SetPosition(Card, new Vector2(SetSize.X - Card.SetSize.X - 10f, 0f));
        LayoutContainer.SetAnchorPreset(Scanlines, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(Vignette, LayoutContainer.LayoutPreset.Wide);
    }

    public void UpdateState(SlasherKitSelectBoundUserInterfaceState state)
    {
        _kits = state.Kits;
        Fill(0, null);
        Rack.SetActive(0);
    }

    private int? ParentOf(int index)
    {
        var need = _kits[index].RequiredAscension;
        if (need == null)
            return null;

        for (var i = 0; i < _kits.Count; i++)
            if (i != index && _kits[i].AscensionId == need)
                return i;

        return null;
    }

    private List<int> ChildrenOf(int? parent)
    {
        var children = new List<int>();
        for (var i = 0; i < _kits.Count; i++)
            if (ParentOf(i) == parent)
                children.Add(i);

        return children;
    }

    private SpinnerRack.Entry MakeEntry(int i, int depth)
    {
        var kit = _kits[i];
        return new SpinnerRack.Entry(
            kit,
            i,
            Loc.GetString(kit.Name),
            _sprites.Frame0(kit.Sprite),
            StorePalette.Spines[i % StorePalette.Spines.Length],
            ChildrenOf(i).Count,
            depth);
    }

    private void Fill(int tier, int? parent)
    {
        Rack.SetTier(tier, ChildrenOf(parent).Select(i => MakeEntry(i, tier)).ToList());
    }

    private void GoTo(int tier)
    {
        if (tier < 0 || tier >= Rack.TierCount || Rack.SelectedOn(tier) == null)
            return;

        Rack.SetActive(tier);
    }

    private void OnRackSelected(int tier, SpinnerRack.Entry entry)
    {
        Fill(tier + 1, entry.Index);

        var trail = new List<string>();
        for (var t = 0; t < tier; t++)
            trail.Add(Rack.SelectedOn(t)?.Name ?? string.Empty);
        Layers.Set(trail);

        var parent = ParentOf(entry.Index);
        var parentName = parent is { } p ? Loc.GetString(_kits[p].Name) : null;
        Card.Show(entry.Kit, parentName, entry.Depth, entry.Sequels);
    }

    private void OpenGuide(ProtoId<GuideEntryPrototype> guide)
    {
        UserInterfaceManager.GetUIController<GuidebookUIController>().OpenGuidebook(selected: guide);
    }
}
