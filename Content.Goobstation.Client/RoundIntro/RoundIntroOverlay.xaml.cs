using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System.Numerics;
using Robust.Shared.Timing;

namespace Content.Goobstation.Client.RoundIntro;

[GenerateTypedNameReferences]
public sealed partial class RoundIntroOverlay : Control
{
    [Dependency] private IResourceCache _cache = default!;

    private const float FadeToBlackTime = 0.8f;
    private const float TextInTime = 0.8f;
    private const float HoldTime = 2.5f;
    private const float CoworkersHoldTime = 4.5f;
    private const int CoworkersPerRow = 6;
    private const float FadeOutTime = 1.5f;

    private readonly Font _coworkerNameFont;
    private readonly Font _coworkerJobFont;

    private readonly List<SpriteView> _spriteViews = new();
    private BoxContainer? _currentRow;
    private int _coworkerCount;

    private RoundIntroPhase _phase;
    private float _elapsed;

    public event Action? FadedToBlack;
    public event Action? Finished;

    public RoundIntroOverlay()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PrefixLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Italic.ttf", 16);
        NameLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 40);
        JobLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 22);
        StationLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Italic.ttf", 14);
        AntagLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 18);
        CoworkersLabel.FontOverride = LoadFont("/Fonts/NotoSans/NotoSans-Italic.ttf", 14);
        _coworkerNameFont = LoadFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 13);
        _coworkerJobFont = LoadFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 11);

        Modulate = Color.White.WithAlpha(0f);
        TextBox.Modulate = Color.White.WithAlpha(0f);
        _spriteViews.Add(SelfView);
        UpdateSpriteAlpha();
    }

    private Font LoadFont(string path, int size)
    {
        return new VectorFont(_cache.GetResource<FontResource>(path), size);
    }

    public void SetText(NetEntity entity, string prefix, string name, string? job, Color jobColor, string? antag, string? station)
    {
        SelfView.SetEntity(entity);
        PrefixLabel.Text = prefix;
        NameLabel.Text = name;
        JobLabel.Text = job ?? string.Empty;
        JobLabel.Visible = job != null;
        JobLabel.FontColorOverride = jobColor;
        AntagLabel.Text = antag ?? string.Empty;
        AntagLabel.Visible = antag != null;
        StationLabel.Text = station ?? string.Empty;
        StationLabel.Visible = station != null;
    }

    public void SetCoworkersTitle(string title)
    {
        CoworkersLabel.Text = title;
    }

    public void AddCoworker(NetEntity entity, string name, string? job)
    {
        var view = new SpriteView
        {
            SetSize = new Vector2(64, 64),
            Scale = new Vector2(2, 2),
            OverrideDirection = Direction.South,
            HorizontalAlignment = HAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        view.SetEntity(entity);
        _spriteViews.Add(view);

        var entry = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            MinWidth = 110,
            MouseFilter = MouseFilterMode.Ignore,
        };
        entry.AddChild(view);
        entry.AddChild(new Label
        {
            Text = name,
            HorizontalAlignment = HAlignment.Center,
            FontOverride = _coworkerNameFont,
            FontColorOverride = Color.White,
        });

        if (job != null)
        {
            entry.AddChild(new Label
            {
                Text = job,
                HorizontalAlignment = HAlignment.Center,
                FontOverride = _coworkerJobFont,
                FontColorOverride = Color.FromHex("#d8c48a"),
            });
        }

        if (_currentRow == null || _coworkerCount % CoworkersPerRow == 0)
        {
            _currentRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalAlignment = HAlignment.Center,
                SeparationOverride = 24,
                MouseFilter = MouseFilterMode.Ignore,
            };
            CoworkersRows.AddChild(_currentRow);
        }

        _currentRow.AddChild(entry);
        _coworkerCount++;
        CoworkersBox.Visible = true;
        UpdateSpriteAlpha();
    }

    public void StartFadeToBlack()
    {
        SetPhase(RoundIntroPhase.FadeToBlack);
    }

    public void StartIntro()
    {
        Modulate = Color.White;
        SetPhase(RoundIntroPhase.TextIn);
    }

    public void StartFadeOut()
    {
        Modulate = Color.White;
        SetPhase(RoundIntroPhase.FadeOut);
    }

    private void SetPhase(RoundIntroPhase phase)
    {
        _phase = phase;
        _elapsed = 0f;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _elapsed += args.DeltaSeconds;

        switch (_phase)
        {
            case RoundIntroPhase.FadeToBlack:
                Modulate = Color.White.WithAlpha(Math.Clamp(_elapsed / FadeToBlackTime, 0f, 1f));
                if (_elapsed < FadeToBlackTime)
                    break;
                SetPhase(RoundIntroPhase.Waiting);
                FadedToBlack?.Invoke();
                break;
            case RoundIntroPhase.TextIn:
                TextBox.Modulate = Color.White.WithAlpha(Math.Clamp(_elapsed / TextInTime, 0f, 1f));
                if (_elapsed >= TextInTime)
                    SetPhase(RoundIntroPhase.Hold);
                break;
            case RoundIntroPhase.Hold:
                if (_elapsed >= (CoworkersBox.Visible ? CoworkersHoldTime : HoldTime))
                    SetPhase(RoundIntroPhase.FadeOut);
                break;
            case RoundIntroPhase.FadeOut:
                Modulate = Color.White.WithAlpha(1f - Math.Clamp(_elapsed / FadeOutTime, 0f, 1f));
                if (_elapsed < FadeOutTime)
                    break;
                SetPhase(RoundIntroPhase.Done);
                Finished?.Invoke();
                break;
        }

        UpdateSpriteAlpha();
    }

    private void UpdateSpriteAlpha()
    {
        var color = Color.White.WithAlpha(Modulate.A * TextBox.Modulate.A);
        foreach (var view in _spriteViews)
        {
            view.Modulate = color;
        }
    }

    private enum RoundIntroPhase : byte
    {
        Waiting,
        FadeToBlack,
        TextIn,
        Hold,
        FadeOut,
        Done,
    }
}
