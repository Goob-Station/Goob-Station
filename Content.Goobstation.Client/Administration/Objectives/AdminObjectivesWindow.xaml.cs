using Content.Goobstation.Shared.Administration.Objectives;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.Administration.Objectives;

[GenerateTypedNameReferences]
public sealed partial class AdminObjectivesWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    private enum TabIndex
    {
        Current = 0,
        Prototype = 1,
        Custom = 2,
        Steal = 3,
    }

    /// <summary>Id of the "random target" entry in the target dropdown.</summary>
    private const int RandomTargetId = 0;

    private readonly SpriteSystem _sprite;

    private const string DefaultIssuer = "objective-issuer-unknown";

    private List<AdminObjectivePrototypeEntry> _prototypes = new();
    private List<AdminObjectiveTargetEntry> _targets = new();
    private List<AdminObjectiveIssuerEntry> _issuers = new();
    private AdminObjectivePrototypeEntry? _selectedProto;
    private NetEntity? _chosenTarget;
    private bool _hasMind = true;
    private string _customIssuer = DefaultIssuer;
    private string _stealIssuer = DefaultIssuer;

    public event Action<string, NetEntity?, bool>? OnAddPrototype;
    public event Action<string, string, string>? OnAddCustom;
    public event Action<NetEntity, string>? OnAddSteal;
    public event Action<NetEntity>? OnRemove;
    public event Action? OnRefresh;

    public AdminObjectivesWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();

        Tabs.SetTabTitle((int) TabIndex.Current, Loc.GetString("admin-objectives-tab-current"));
        Tabs.SetTabTitle((int) TabIndex.Prototype, Loc.GetString("admin-objectives-tab-prototype"));
        Tabs.SetTabTitle((int) TabIndex.Custom, Loc.GetString("admin-objectives-tab-custom"));
        Tabs.SetTabTitle((int) TabIndex.Steal, Loc.GetString("admin-objectives-tab-steal"));

        CustomTitle.IsValid = text => text.Length <= AdminObjectivesLimits.MaxTitleLength;

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        ProtoSearch.OnTextChanged += _ => PopulatePrototypes();
        ProtoList.OnItemSelected += args =>
        {
            _selectedProto = (AdminObjectivePrototypeEntry) args.ItemList[args.ItemIndex].Metadata!;
            UpdateProtoSelection();
        };
        ProtoList.OnItemDeselected += _ =>
        {
            _selectedProto = null;
            UpdateProtoSelection();
        };

        TargetOption.OnItemSelected += args =>
        {
            TargetOption.SelectId(args.Id);
            _chosenTarget = args.Id > RandomTargetId && args.Id - 1 < _targets.Count
                ? _targets[args.Id - 1].Mind
                : null;
        };
        CustomIssuer.OnItemSelected += args =>
        {
            CustomIssuer.SelectId(args.Id);
            _customIssuer = GetIssuerId(args.Id);
        };
        StealIssuer.OnItemSelected += args =>
        {
            StealIssuer.SelectId(args.Id);
            _stealIssuer = GetIssuerId(args.Id);
        };

        AddProtoButton.OnPressed += _ => AddPrototype();
        AddCustomButton.OnPressed += _ => AddCustom();
        AddStealButton.OnPressed += _ => AddSteal();

        UpdateProtoSelection();
    }

    public void UpdateState(AdminObjectivesEuiState state)
    {
        PlayerLabel.Text = state.HasMind
            ? Loc.GetString("admin-objectives-player", ("player", state.PlayerName))
            : Loc.GetString("admin-objectives-no-mind", ("player", state.PlayerName));

        // all the add buttons are pointless without a mind to add to
        _hasMind = state.HasMind;
        AddCustomButton.Disabled = !state.HasMind;
        AddStealButton.Disabled = !state.HasMind;

        ObjectiveList.RemoveAllChildren();
        if (state.Objectives.Count == 0)
        {
            ObjectiveList.AddChild(new Label
            {
                Text = Loc.GetString("admin-objectives-none"),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var entry in state.Objectives)
        {
            var row = new AdminObjectiveRow(entry, _sprite);
            row.OnRemove += objective => OnRemove?.Invoke(objective);
            ObjectiveList.AddChild(row);
        }

        _prototypes = state.Prototypes;
        _targets = state.Targets;
        _issuers = state.Issuers;

        PopulatePrototypes();
        PopulateTargets();
        PopulateIssuers(CustomIssuer, _customIssuer);
        PopulateIssuers(StealIssuer, _stealIssuer);
    }

    /// <summary>
    /// Shows the result of the last action and clears the custom objective inputs if it was added.
    /// </summary>
    public void HandleResult(string message, bool success)
    {
        StatusLabel.Text = message;
        StatusLabel.FontColorOverride = success ? Color.LightGreen : Color.OrangeRed;

        if (success && Tabs.CurrentTab == (int) TabIndex.Custom)
        {
            CustomTitle.Text = string.Empty;
            CustomDescription.TextRope = new Rope.Leaf(string.Empty);
        }
    }

    private void PopulatePrototypes()
    {
        var filter = ProtoSearch.Text.Trim();
        var selectedId = _selectedProto?.Id;
        AdminObjectivePrototypeEntry? reselected = null;

        ProtoList.Clear();
        foreach (var proto in _prototypes)
        {
            if (filter.Length > 0 &&
                !proto.Id.Contains(filter, StringComparison.InvariantCultureIgnoreCase) &&
                !proto.Name.Contains(filter, StringComparison.InvariantCultureIgnoreCase))
            {
                continue;
            }

            var item = ProtoList.AddItem(proto.Id);
            item.Metadata = proto;
            if (proto.Id != selectedId)
                continue;

            item.Selected = true;
            reselected = proto;
        }

        // the selection is lost if the filter hid it or the prototype is gone
        _selectedProto = reselected;
        UpdateProtoSelection();
    }

    private void PopulateTargets()
    {
        TargetOption.Clear();
        TargetOption.AddItem(Loc.GetString("admin-objectives-target-random"), RandomTargetId);

        var found = false;
        for (var i = 0; i < _targets.Count; i++)
        {
            var target = _targets[i];
            var text = Loc.GetString("admin-objectives-target-entry",
                ("name", target.CharacterName),
                ("job", target.Job),
                ("dead", target.Dead ? "true" : "false"));

            // ids are index + 1 so that 0 stays "random"
            TargetOption.AddItem(text, i + 1);
            if (target.Mind != _chosenTarget)
                continue;

            TargetOption.SelectId(i + 1);
            found = true;
        }

        if (found)
            return;

        // the chosen target left the round
        _chosenTarget = null;
        TargetOption.SelectId(RandomTargetId);
    }

    private void PopulateIssuers(OptionButton option, string chosen)
    {
        option.Clear();
        for (var i = 0; i < _issuers.Count; i++)
        {
            option.AddItem(_issuers[i].Name, i);
        }

        var index = _issuers.FindIndex(i => i.Id == chosen);
        if (index < 0)
            index = _issuers.FindIndex(i => i.Id == DefaultIssuer);

        if (index >= 0)
            option.SelectId(index);
    }

    private string GetIssuerId(int index)
    {
        return index >= 0 && index < _issuers.Count ? _issuers[index].Id : DefaultIssuer;
    }

    private void UpdateProtoSelection()
    {
        AddProtoButton.Disabled = !_hasMind || _selectedProto == null;
        ProtoNameLabel.Text = _selectedProto == null
            ? Loc.GetString("admin-objectives-nothing-selected")
            : Loc.GetString("admin-objectives-selected", ("proto", _selectedProto.Id), ("name", _selectedProto.Name));
        TargetBox.Visible = _selectedProto is { HasTarget: true };
    }

    private void AddPrototype()
    {
        if (_selectedProto == null)
            return;

        var target = _selectedProto.HasTarget ? _chosenTarget : null;
        OnAddPrototype?.Invoke(_selectedProto.Id, target, BypassCheck.Pressed);
    }

    private void AddCustom()
    {
        OnAddCustom?.Invoke(CustomTitle.Text, Rope.Collapse(CustomDescription.TextRope), _customIssuer);
    }

    private void AddSteal()
    {
        if (!NetEntity.TryParse(StealEntity.Text.Trim(), out var item))
        {
            HandleResult(Loc.GetString("admin-objectives-error-bad-entity-id"), false);
            return;
        }

        OnAddSteal?.Invoke(item, _stealIssuer);
    }
}
