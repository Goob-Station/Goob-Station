using System.Linq;
using Content.Goobstation.Common.CCVar;
using Content.Goobstation.UIKit.UserInterface.Lobby;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Goobstation.UIKit.UserInterface.Humanoid;

[GenerateTypedNameReferences]
public sealed partial class MarkingTilePicker : BoxContainer
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private MarkingManager _markingManager = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly TimeSpan ColorCommitInterval = TimeSpan.FromSeconds(0.12);

    private static readonly Color[] Presets =
    {
        Color.FromHex("#141414"), Color.FromHex("#3b2a1f"), Color.FromHex("#5a3a22"), Color.FromHex("#7b4a2a"),
        Color.FromHex("#8f3b1f"), Color.FromHex("#c4692e"), Color.FromHex("#d8b05a"), Color.FromHex("#efe2b5"),
        Color.FromHex("#9a9a9a"), Color.FromHex("#e8e8e8"),
    };

    public Action<(int slot, string id)>? OnMarkingSelect;
    public Action<int>? OnSlotRemove;
    public Action? OnSlotAdd;
    public Action<(int slot, Marking marking)>? OnColorChanged;
    public event Action<string?>? OnMarkingHover;
    public event Action? OnMarkingHoverEnd;

    private readonly SpriteSystem _sprite;
    private readonly TileBaseDoll _doll;
    private readonly MarkingTileColors _colors = new();
    private readonly List<MarkingTile> _tiles = new();
    private readonly HashSet<string> _favourites = new();
    private readonly List<ColorSwatch> _swatches = new();

    private MarkingCategories _category;
    private string? _species;
    private string? _builtFor;
    private List<Marking> _markings = new();

    private Marking? _pendingColor;
    private TimeSpan _lastColorCommit;

    private bool _hoverActive;
    private string? _hoverId;
    private bool _hoverDirty;

    public int OptionCount { get; private set; }

    public MarkingCategories Category
    {
        get => _category;
        set
        {
            _category = value;
            _builtFor = null;
            if (_species != null)
                Rebuild();
        }
    }

    public MarkingTilePicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();
        _doll = new TileBaseDoll(_entMan, _proto);

        foreach (var id in _cfg.GetCVar(GoobCVars.MarkingFavourites).Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            _favourites.Add(id);
        }

        Search.OnTextChanged += _ => ApplyFilter();
        AllButton.OnPressed += _ => SetFavouritesOnly(false);
        FavouritesButton.OnPressed += _ => SetFavouritesOnly(true);
        CustomButton.OnToggled += args => ColorSelectorContainer.Visible = args.Pressed;

        foreach (var color in Presets)
        {
            var swatch = new ColorSwatch(color);
            swatch.OnPressed += _ => ApplyPreset(color);
            _swatches.Add(swatch);
            Swatches.AddChild(swatch);
        }

        UpdateFavouritesLabel();
    }

    public void UpdateData(List<Marking> markings, string species, int totalPoints)
    {
        _markings = markings;
        _species = species;

        if (_doll.EnsureSpecies(species))
            _builtFor = null;

        if (_markings.Count > 0)
            _colors.Marking = new List<Color>(_markings[0].MarkingColors);

        if (_builtFor != BuildKey)
            Rebuild();

        UpdateSelection();
        PopulateColors();
    }

    public void SetPreviewProfile(HumanoidCharacterProfile profile)
    {
        var appearance = _category == MarkingCategories.FacialHair
            ? profile.Appearance.WithFacialHairStyleName(HairStyles.DefaultFacialHairStyle)
            : profile.Appearance.WithHairStyleName(HairStyles.DefaultHairStyle);

        _doll.Queue(profile.WithCharacterAppearance(appearance));
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _doll.Dispose();
    }

    public void SetAppearanceColors(Color skin, Color eyes, Color marking)
    {
        _colors.Skin = skin;
        _colors.Eyes = eyes;

        if (_markings.Count == 0 || _markings[0].MarkingColors.Count <= 1)
            _colors.Marking = new List<Color> { marking };

        UpdateSwatches();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _doll.Update(_timing.RealTime);

        if (_pendingColor is { } pending && _timing.RealTime - _lastColorCommit >= ColorCommitInterval)
        {
            _pendingColor = null;
            _lastColorCommit = _timing.RealTime;
            OnColorChanged?.Invoke((0, pending));
        }

        if (!_hoverDirty)
            return;

        _hoverDirty = false;
        if (_hoverActive)
            OnMarkingHover?.Invoke(_hoverId);
        else
            OnMarkingHoverEnd?.Invoke();
    }

    private string BuildKey => $"{_species}/{_category}";

    private void Rebuild()
    {
        Grid.RemoveAllChildren();
        _tiles.Clear();
        _builtFor = BuildKey;

        if (_species == null)
            return;

        var options = _markingManager.MarkingsByCategoryAndSpecies(_category, _species);
        OptionCount = options.Count;

        var region = _category == MarkingCategories.FacialHair
            ? new UIBox2(0.25f, 0.08f, 0.75f, 0.58f)
            : new UIBox2(0.25f, 0f, 0.75f, 0.5f);

        AddTile(null, Loc.GetString("marking-tiles-none"), new List<MarkingTileLayer>(), region);

        foreach (var (id, proto) in options.OrderBy(p => Loc.GetString($"marking-{p.Key}")))
        {
            var layers = new List<MarkingTileLayer>();
            for (var i = 0; i < proto.Sprites.Count; i++)
            {
                layers.Add(new MarkingTileLayer(_sprite.Frame0(proto.Sprites[i]), proto.FollowSkinColor ? MarkingTileTint.Skin : MarkingTileTint.Marking, i, HumanoidTileArt.SlotFor(proto, i)));
            }

            AddTile(id, Loc.GetString($"marking-{id}"), layers, region);
        }

        UpdateFavouritesLabel();
        ApplyFilter();
    }

    private void AddTile(string? id, string name, List<MarkingTileLayer> layers, UIBox2 region)
    {
        var tile = new MarkingTile(id, name, _colors, layers, region, _doll.Entity)
        {
            Favourite = id != null && _favourites.Contains(id),
        };

        tile.OnPressed += _ => Select(tile.MarkingId);
        tile.OnMouseEntered += _ => SetHover(true, tile.MarkingId);
        tile.OnMouseExited += _ => SetHover(false, null);
        tile.RightClicked += ToggleFavourite;

        _tiles.Add(tile);
        Grid.AddChild(tile);
    }

    private void Select(string? id)
    {
        if (id == null)
        {
            if (_markings.Count > 0)
                OnSlotRemove?.Invoke(0);

            UpdateSelection();
            PopulateColors();
            return;
        }

        if (_markings.Count == 0)
            OnSlotAdd?.Invoke();

        if (_markings.Count == 0 || !_markingManager.Markings.TryGetValue(id, out var proto))
        {
            UpdateSelection();
            return;
        }

        var old = _markings[0];
        var marking = proto.AsMarking();
        for (var i = 0; i < marking.MarkingColors.Count && i < old.MarkingColors.Count; i++)
        {
            marking.SetColor(i, old.MarkingColors[i]);
        }

        _markings[0] = marking;
        OnMarkingSelect?.Invoke((0, id));

        UpdateSelection();
        PopulateColors();
    }

    private void UpdateSelection()
    {
        var current = _markings.Count > 0 ? _markings[0].MarkingId : null;
        foreach (var tile in _tiles)
        {
            tile.Pressed = tile.MarkingId == current;
        }
    }

    private void PopulateColors()
    {
        ColorSelectorContainer.RemoveAllChildren();

        if (_markings.Count == 0 || !_markingManager.TryGetMarking(_markings[0], out var proto))
        {
            ColorRow.Visible = false;
            ColorSelectorContainer.Visible = false;
            return;
        }

        ColorRow.Visible = true;
        ColorSelectorContainer.Visible = CustomButton.Pressed;

        var marking = _markings[0];
        if (marking.MarkingColors.Count != proto.Sprites.Count)
            marking = new Marking(marking.MarkingId, proto.Sprites.Count);

        for (var i = 0; i < marking.MarkingColors.Count; i++)
        {
            var selector = new ColorSelectorSliders
            {
                HorizontalExpand = true,
                Color = marking.MarkingColors[i],
                SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv,
            };

            var layer = i;
            selector.OnColorChanged += color =>
            {
                marking.SetColor(layer, color);
                _colors.Marking = new List<Color>(marking.MarkingColors);
                UpdateSwatches();
                _pendingColor = marking;
            };

            ColorSelectorContainer.AddChild(selector);
        }

        UpdateSwatches();
    }

    private void ApplyPreset(Color color)
    {
        if (_markings.Count == 0)
        {
            UpdateSwatches();
            return;
        }

        var marking = _markings[0];
        for (var i = 0; i < marking.MarkingColors.Count; i++)
        {
            marking.SetColor(i, color);
        }

        _colors.Marking = new List<Color>(marking.MarkingColors);
        OnColorChanged?.Invoke((0, marking));
        PopulateColors();
    }

    private void UpdateSwatches()
    {
        var current = _colors.Marking.Count > 0 ? _colors.Marking[0] : Color.White;
        foreach (var swatch in _swatches)
        {
            swatch.Pressed = swatch.Matches(current);
        }
    }

    private void SetHover(bool active, string? id)
    {
        if (_hoverActive == active && _hoverId == id)
            return;

        _hoverActive = active;
        _hoverId = id;
        _hoverDirty = true;
    }

    private void SetFavouritesOnly(bool favouritesOnly)
    {
        AllButton.Pressed = !favouritesOnly;
        FavouritesButton.Pressed = favouritesOnly;
        ApplyFilter();
    }

    private void ToggleFavourite(MarkingTile tile)
    {
        if (tile.MarkingId is not { } id)
            return;

        if (!_favourites.Add(id))
            _favourites.Remove(id);

        tile.Favourite = _favourites.Contains(id);
        _cfg.SetCVar(GoobCVars.MarkingFavourites, string.Join(',', _favourites));
        _cfg.SaveToFile();

        UpdateFavouritesLabel();
        if (FavouritesButton.Pressed)
            ApplyFilter();
    }

    private void UpdateFavouritesLabel()
    {
        var count = _tiles.Count(t => t.MarkingId != null && _favourites.Contains(t.MarkingId));
        FavouritesButton.Text = Loc.GetString("marking-tiles-favourites", ("count", count));
    }

    private void ApplyFilter()
    {
        var filter = Search.Text.Trim();
        var favouritesOnly = FavouritesButton.Pressed;
        var shown = 0;

        foreach (var tile in _tiles)
        {
            var visible = tile.MarkingId == null
                ? !favouritesOnly && filter.Length == 0
                : (!favouritesOnly || _favourites.Contains(tile.MarkingId))
                  && (filter.Length == 0
                      || tile.DisplayName.Contains(filter, StringComparison.OrdinalIgnoreCase)
                      || tile.MarkingId.Contains(filter, StringComparison.OrdinalIgnoreCase));

            tile.Visible = visible;
            if (visible)
                shown++;
        }

        EmptyLabel.Visible = shown == 0;
        EmptyLabel.Text = Loc.GetString(favouritesOnly ? "marking-tiles-no-favourites" : "marking-tiles-no-match");
    }

}
