namespace Content.Goobstation.UIKit.UserInterface.Humanoid;

[GenerateTypedNameReferences]
public sealed partial class MarkingGridPicker : BoxContainer
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private MarkingManager _markingManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly TimeSpan ColorCommitInterval = TimeSpan.FromSeconds(0.12);

    public Action<MarkingSet>? OnMarkingAdded;
    public Action<MarkingSet>? OnMarkingRemoved;
    public Action<MarkingSet>? OnMarkingColorChange;
    public Action<MarkingSet>? OnMarkingRankChange;
    public event Action<MarkingSet>? OnMarkingPreview;
    public event Action? OnMarkingPreviewEnd;

    public Color CurrentSkinColor = Color.White;
    public Color CurrentEyeColor = Color.Black;
    public Marking? HairMarking;
    public Marking? FacialHairMarking;

    private readonly SpriteSystem _sprite;
    private readonly TileBaseDoll _doll;
    private HumanoidCharacterProfile? _previewProfile;
    private readonly List<MarkingCategories> _categories = Enum.GetValues<MarkingCategories>().ToList();
    private readonly HashSet<MarkingCategories> _ignoreCategories = new();
    private readonly List<(MarkingTile Tile, MarkingTileColors Colors, MarkingPrototype Proto)> _tiles = new();

    private MarkingSet _currentMarkings = new();
    private MarkingCategories _selectedCategory = MarkingCategories.Chest;
    private string _currentSpecies = SharedHumanoidAppearanceSystem.DefaultSpecies;
    private Sex _currentSex = Sex.Unsexed;
    private string? _builtFor;
    private (MarkingCategories Category, string Id)? _editing;

    private Color? _tileSkin;
    private Color? _tileEyes;

    private bool _colorPending;
    private TimeSpan _lastColorCommit;

    private bool _hoverActive;
    private string? _hoverId;
    private bool _hoverDirty;

    public string IgnoreCategories
    {
        get => string.Join(',', _ignoreCategories);
        set
        {
            _ignoreCategories.Clear();
            foreach (var category in value.Split(','))
            {
                if (Enum.TryParse(category, out MarkingCategories parsed))
                    _ignoreCategories.Add(parsed);
            }

            SetupCategoryChips();
        }
    }

    public bool Forced { get; set; }

    private bool _ignoreSpecies;

    public bool IgnoreSpecies
    {
        get => _ignoreSpecies;
        set
        {
            _ignoreSpecies = value;
            _builtFor = null;
            Populate(Search.Text);
        }
    }

    public MarkingGridPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();
        _doll = new TileBaseDoll(_entMan, _prototypeManager);

        Search.OnTextChanged += args => Populate(args.Text);
    }

    public void SetData(List<Marking> newMarkings, string species, Sex sex, Color skinColor, Color eyeColor)
    {
        var pointsProto = _prototypeManager.Index<SpeciesPrototype>(species).MarkingPoints;
        _currentMarkings = new MarkingSet(newMarkings, pointsProto, _markingManager);
        if (!IgnoreSpecies)
            _currentMarkings.EnsureSpecies(species, skinColor, _markingManager);

        ApplyData(species, sex, skinColor, eyeColor);
    }

    public void SetData(MarkingSet set, string species, Sex sex, Color skinColor, Color eyeColor)
    {
        _currentMarkings = set;
        if (!IgnoreSpecies)
            _currentMarkings.EnsureSpecies(species, skinColor, _markingManager);

        ApplyData(species, sex, skinColor, eyeColor);
    }

    public void SetSkinColor(Color color) => SetAppearanceColors(color, CurrentEyeColor);

    public void SetEyeColor(Color color) => SetAppearanceColors(CurrentSkinColor, color);

    public void SetAppearanceColors(Color skin, Color eyes)
    {
        if (_tileSkin == skin && _tileEyes == eyes)
            return;

        CurrentSkinColor = skin;
        CurrentEyeColor = eyes;
        RefreshTileColors();
    }

    public void SetPreviewProfile(HumanoidCharacterProfile profile)
    {
        _previewProfile = profile;
        QueueDoll();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _doll.Dispose();
    }

    public void SetSpecies(string species)
    {
        _currentSpecies = species;
        Rebase();
    }

    public void SetSex(Sex sex)
    {
        _currentSex = sex;
        Rebase();
    }

    public void Populate(string filter)
    {
        SetupCategoryChips();

        if (_builtFor != BuildKey)
            BuildTiles();

        var trimmed = filter.Trim();
        var shown = 0;
        foreach (var (tile, _, proto) in _tiles)
        {
            var visible = trimmed.Length == 0
                          || tile.DisplayName.Contains(trimmed, StringComparison.OrdinalIgnoreCase)
                          || proto.ID.Contains(trimmed, StringComparison.OrdinalIgnoreCase);
            tile.Visible = visible;
            if (visible)
                shown++;
        }

        EmptyLabel.Visible = shown == 0;
        RefreshTileStates();
        UpdatePoints();
    }

    public void PopulateUsed()
    {
        AppliedList.RemoveAllChildren();

        if (!IgnoreSpecies)
            _currentMarkings.EnsureSpecies(_currentSpecies, null, _markingManager);

        var any = false;
        foreach (var category in _categories)
        {
            if (_ignoreCategories.Contains(category) || !_currentMarkings.Markings.TryGetValue(category, out var list))
                continue;

            for (var i = list.Count - 1; i >= 0; i--)
            {
                if (!_markingManager.TryGetMarking(list[i], out var proto))
                    continue;

                AppliedList.AddChild(CreateAppliedRow(category, list.Count - 1 - i, list.Count, list[i], proto));
                any = true;
            }
        }

        AppliedEmpty.Visible = !any;

        if (_editing is { } editing && _currentMarkings.FindIndexOf(editing.Category, editing.Id) < 0)
            _editing = null;

        PopulateColorEditor();
        RefreshTileStates();
        UpdatePoints();
        SetupCategoryChips();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _doll.Update(_timing.RealTime);

        if (_colorPending && _timing.RealTime - _lastColorCommit >= ColorCommitInterval)
        {
            _colorPending = false;
            _lastColorCommit = _timing.RealTime;
            OnMarkingColorChange?.Invoke(_currentMarkings);
        }

        if (!_hoverDirty)
            return;

        _hoverDirty = false;
        if (_hoverActive && _hoverId != null && _markingManager.Markings.TryGetValue(_hoverId, out var proto)
            && _currentMarkings.FindIndexOf(proto.MarkingCategory, proto.ID) < 0
            && (Forced || _currentMarkings.PointsLeft(proto.MarkingCategory) != 0))
        {
            var preview = new MarkingSet(_currentMarkings);
            preview.AddBack(proto.MarkingCategory, CreateMarking(proto));
            OnMarkingPreview?.Invoke(preview);
            return;
        }

        OnMarkingPreviewEnd?.Invoke();
    }

    private string BuildKey => $"{_currentSpecies}/{_currentSex}/{_selectedCategory}/{IgnoreSpecies}";

    private void ApplyData(string species, Sex sex, Color skinColor, Color eyeColor)
    {
        _currentSpecies = species;
        _currentSex = sex;
        CurrentSkinColor = skinColor;
        CurrentEyeColor = eyeColor;
        Populate(Search.Text);
        PopulateUsed();
        RefreshTileColors();
    }

    private void Rebase()
    {
        var markingList = _currentMarkings.GetForwardEnumerator().ToList();
        var speciesPrototype = _prototypeManager.Index<SpeciesPrototype>(_currentSpecies);
        _currentMarkings = new MarkingSet(markingList, speciesPrototype.MarkingPoints, _markingManager, _prototypeManager);
        _currentMarkings.EnsureSpecies(_currentSpecies, null, _markingManager);
        _currentMarkings.EnsureSexes(_currentSex, _markingManager);
        Populate(Search.Text);
        PopulateUsed();
    }

    private IReadOnlyDictionary<string, MarkingPrototype> GetMarkings(MarkingCategories category)
    {
        return IgnoreSpecies
            ? _markingManager.MarkingsByCategoryAndSex(category, _currentSex)
            : _markingManager.MarkingsByCategoryAndSpeciesAndSex(category, _currentSpecies, _currentSex);
    }

    private void SetupCategoryChips()
    {
        CategoryChips.RemoveAllChildren();

        var valid = _categories.Where(c => !_ignoreCategories.Contains(c) && GetMarkings(c).Count > 0).ToList();
        if (!valid.Contains(_selectedCategory) && valid.Count > 0)
            _selectedCategory = valid[0];

        foreach (var category in valid)
        {
            var name = Loc.GetString($"markings-category-{category}");
            var left = _currentMarkings.PointsLeft(category);
            var used = _currentMarkings.Markings.TryGetValue(category, out var list) ? list.Count : 0;

            var chip = new Button
            {
                ToggleMode = true,
                Pressed = category == _selectedCategory,
                StyleClasses = { HullStyleClasses.Tab },
                Text = left < 0 ? name : Loc.GetString("marking-grid-category-count", ("name", name), ("used", used), ("total", used + left)),
            };

            chip.OnPressed += _ =>
            {
                _selectedCategory = category;
                Populate(Search.Text);
            };

            CategoryChips.AddChild(chip);
        }
    }

    private void BuildTiles()
    {
        Grid.RemoveAllChildren();
        _tiles.Clear();
        _builtFor = BuildKey;

        _doll.EnsureSpecies(_currentSpecies);
        QueueDoll();

        var region = HumanoidTileArt.IsHeadCategory(_selectedCategory) ? HumanoidTileArt.HeadRegion : HumanoidTileArt.FullBody;

        foreach (var proto in GetMarkings(_selectedCategory).Values.OrderBy(p => Loc.GetString($"marking-{p.ID}")))
        {
            var layers = new List<MarkingTileLayer>();
            for (var i = 0; i < proto.Sprites.Count; i++)
            {
                layers.Add(new MarkingTileLayer(_sprite.Frame0(proto.Sprites[i]), MarkingTileTint.Marking, i, HumanoidTileArt.SlotFor(proto, i)));
            }

            var colors = new MarkingTileColors();
            var tile = new MarkingTile(proto.ID, Loc.GetString($"marking-{proto.ID}"), colors, layers, region, _doll.Entity, MarkingTile.WideTileWidth);
            tile.OnPressed += _ => ToggleMarking(proto);
            tile.OnMouseEntered += _ => SetHover(true, proto.ID);
            tile.OnMouseExited += _ => SetHover(false, null);

            _tiles.Add((tile, colors, proto));
            Grid.AddChild(tile);
        }

        RefreshTileColors();
    }

    private void QueueDoll()
    {
        if (_previewProfile is not { } profile)
            return;

        var kept = profile.Appearance.Markings
            .Where(m => !_markingManager.Markings.TryGetValue(m.MarkingId, out var proto) || proto.MarkingCategory != _selectedCategory)
            .ToList();

        _doll.Queue(profile.WithCharacterAppearance(profile.Appearance.WithMarkings(kept)));
    }

    private void RefreshTileStates()
    {
        foreach (var (tile, _, proto) in _tiles)
        {
            tile.Pressed = _currentMarkings.FindIndexOf(proto.MarkingCategory, proto.ID) >= 0;
        }
    }

    private void RefreshTileColors()
    {
        _tileSkin = CurrentSkinColor;
        _tileEyes = CurrentEyeColor;
        var context = ColorContext();

        foreach (var (_, colors, proto) in _tiles)
        {
            colors.Skin = CurrentSkinColor;
            colors.Eyes = CurrentEyeColor;

            var index = _currentMarkings.FindIndexOf(proto.MarkingCategory, proto.ID);
            colors.Marking = index >= 0
                ? new List<Color>(_currentMarkings.Markings[proto.MarkingCategory][index].MarkingColors)
                : new List<Color>(CreateMarking(proto, context).MarkingColors);
        }
    }

    private MarkingSet ColorContext()
    {
        var context = new MarkingSet(_currentMarkings);
        if (HairMarking != null)
            context.AddBack(MarkingCategories.Hair, HairMarking);
        if (FacialHairMarking != null)
            context.AddBack(MarkingCategories.FacialHair, FacialHairMarking);

        return context;
    }

    private Marking CreateMarking(MarkingPrototype proto, MarkingSet? context = null)
    {
        var marking = proto.AsMarking();

        if (_markingManager.MustMatchSkin(_currentSpecies, proto.BodyPart, out _, _prototypeManager))
        {
            for (var i = 0; i < proto.Sprites.Count; i++)
            {
                marking.SetColor(i, CurrentSkinColor);
            }

            return marking;
        }

        var colors = MarkingColoring.GetMarkingLayerColors(proto, CurrentSkinColor, CurrentEyeColor, context ?? ColorContext());
        for (var i = 0; i < colors.Count; i++)
        {
            marking.SetColor(i, colors[i]);
        }

        return marking;
    }

    private void ToggleMarking(MarkingPrototype proto)
    {
        if (_currentMarkings.FindIndexOf(proto.MarkingCategory, proto.ID) >= 0)
        {
            RemoveMarking(proto.MarkingCategory, proto.ID);
            return;
        }

        if (_currentMarkings.PointsLeft(proto.MarkingCategory) == 0 && !Forced)
        {
            RefreshTileStates();
            return;
        }

        var marking = CreateMarking(proto);
        marking.Forced = Forced;
        _currentMarkings.AddBack(proto.MarkingCategory, marking);
        _editing = (proto.MarkingCategory, proto.ID);

        OnMarkingAdded?.Invoke(_currentMarkings);
        PopulateUsed();
        RefreshTileColors();
        SetHover(false, null);
    }

    private void RemoveMarking(MarkingCategories category, string id)
    {
        _currentMarkings.Remove(category, id);
        if (_editing is { } editing && editing.Category == category && editing.Id == id)
            _editing = null;

        OnMarkingRemoved?.Invoke(_currentMarkings);
        PopulateUsed();
        RefreshTileColors();
    }

    private Control CreateAppliedRow(MarkingCategories category, int reverseIndex, int count, Marking marking, MarkingPrototype proto)
    {
        var row = new ContainerButton
        {
            ToggleMode = true,
            Pressed = _editing is { } editing && editing.Category == category && editing.Id == proto.ID,
            StyleClasses = { HullStyleClasses.Slot },
        };

        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        content.AddChild(new PanelContainer
        {
            SetSize = new Vector2(16, 16),
            VerticalAlignment = VAlignment.Top,
            Margin = new Thickness(0, 2, 0, 0),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = marking.MarkingColors.Count > 0 ? marking.MarkingColors[0] : Color.White,
                BorderColor = HullPanel.EdgeColor,
                BorderThickness = new Thickness(1),
            },
            MouseFilter = MouseFilterMode.Ignore,
        });

        var details = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 2 };
        var title = new RichTextLabel { HorizontalExpand = true, MouseFilter = MouseFilterMode.Ignore };
        title.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(marking.Forced ? "marking-grid-applied-forced" : "marking-grid-applied-name", ("name", Loc.GetString($"marking-{proto.ID}")))));
        details.AddChild(title);

        var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        actions.AddChild(new Label
        {
            Text = Loc.GetString($"markings-category-{category}"),
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
            StyleClasses = { HullStyleClasses.PostDate },
        });
        details.AddChild(actions);
        content.AddChild(details);

        var up = new Button { Text = "▲", StyleClasses = { HullStyleClasses.Plate }, Disabled = reverseIndex == 0 };
        var down = new Button { Text = "▼", StyleClasses = { HullStyleClasses.Plate }, Disabled = reverseIndex >= count - 1 };
        var remove = new Button { Text = Loc.GetString("marking-grid-remove"), StyleClasses = { HullStyleClasses.Plate } };

        up.OnPressed += _ =>
        {
            _currentMarkings.ShiftRankDownFromEnd(category, reverseIndex);
            OnMarkingRankChange?.Invoke(_currentMarkings);
            PopulateUsed();
        };
        down.OnPressed += _ =>
        {
            _currentMarkings.ShiftRankUpFromEnd(category, reverseIndex);
            OnMarkingRankChange?.Invoke(_currentMarkings);
            PopulateUsed();
        };
        remove.OnPressed += _ => RemoveMarking(category, proto.ID);

        actions.AddChild(up);
        actions.AddChild(down);
        actions.AddChild(remove);
        row.AddChild(content);

        row.OnPressed += _ =>
        {
            _editing = (category, proto.ID);
            PopulateUsed();
        };

        return row;
    }

    private void PopulateColorEditor()
    {
        ColorEditor.RemoveAllChildren();
        ColorEditor.Visible = false;

        if (_editing is not { } editing
            || !_markingManager.Markings.TryGetValue(editing.Id, out var proto)
            || proto.ForcedColoring)
        {
            return;
        }

        var index = _currentMarkings.FindIndexOf(editing.Category, editing.Id);
        if (index < 0)
            return;

        var stateNames = GetMarkingStateNames(proto);
        var current = _currentMarkings.Markings[editing.Category][index];

        ColorEditor.AddChild(new Label
        {
            Text = Loc.GetString("marking-grid-colors", ("name", Loc.GetString($"marking-{proto.ID}"))),
            StyleClasses = { HullStyleClasses.Section },
        });

        for (var i = 0; i < proto.Sprites.Count && i < current.MarkingColors.Count; i++)
        {
            if (IsColorLinked(proto, i))
                continue;

            var selector = new ColorSelectorSliders
            {
                SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv,
                Color = new Color(current.MarkingColors[i].RByte, current.MarkingColors[i].GByte, current.MarkingColors[i].BByte),
            };

            var layer = i;
            selector.OnColorChanged += color => SetMarkingColor(editing.Category, editing.Id, layer, color);

            ColorEditor.AddChild(new Label { Text = Loc.GetString("marking-grid-layer-color", ("layer", stateNames[i])), StyleClasses = { HullStyleClasses.FieldLabel } });
            ColorEditor.AddChild(selector);
        }

        ColorEditor.Visible = ColorEditor.ChildCount > 1;
    }

    private void SetMarkingColor(MarkingCategories category, string id, int layer, Color color)
    {
        var index = _currentMarkings.FindIndexOf(category, id);
        if (index < 0)
            return;

        var marking = new Marking(_currentMarkings.Markings[category][index]);
        marking.SetColor(layer, color);
        _currentMarkings.Replace(category, index, marking);
        _colorPending = true;

        foreach (var (_, colors, proto) in _tiles)
        {
            if (proto.ID == id)
                colors.Marking = new List<Color>(marking.MarkingColors);
        }
    }

    private static bool IsColorLinked(MarkingPrototype proto, int layer)
    {
        if (proto.ColorLinks is not { Count: > 0 })
            return false;

        var name = proto.Sprites[layer] switch
        {
            SpriteSpecifier.Rsi rsi => rsi.RsiState,
            SpriteSpecifier.Texture texture => texture.TexturePath.Filename,
            _ => null,
        };

        return name != null && proto.ColorLinks.ContainsKey(name);
    }

    private static List<string> GetMarkingStateNames(MarkingPrototype marking)
    {
        var result = new List<string>();
        foreach (var state in marking.Sprites)
        {
            result.Add(state switch
            {
                SpriteSpecifier.Rsi rsi => Loc.GetString($"marking-{marking.ID}-{rsi.RsiState}"),
                SpriteSpecifier.Texture texture => Loc.GetString($"marking-{marking.ID}-{texture.TexturePath.Filename}"),
                _ => string.Empty,
            });
        }

        return result;
    }

    private void UpdatePoints()
    {
        var count = _currentMarkings.PointsLeft(_selectedCategory);
        PointsLabel.Visible = count > -1;
        if (count > -1)
            PointsLabel.Text = Loc.GetString("marking-points-remaining", ("points", count));
    }

    private void SetHover(bool active, string? id)
    {
        if (_hoverActive == active && _hoverId == id)
            return;

        _hoverActive = active;
        _hoverId = id;
        _hoverDirty = true;
    }

}
