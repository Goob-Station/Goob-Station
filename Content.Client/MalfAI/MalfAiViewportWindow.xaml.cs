using System.Numerics;
using Content.Client.Eye;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Map;
using Robust.Shared.Timing;

namespace Content.Client.MalfAI;

[GenerateTypedNameReferences]
public sealed partial class MalfAiViewportWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    private readonly EyeLerpingSystem _eyeLerpingSystem;

    // Configurable zoom factor (1 = default world scale, <1 zooms in, >1 zooms out)
    private const float DefaultZoom = 0.75f;

    private FixedEye? _staticEye;
    private readonly NetEntity? _anchorEntity;
    private EntityUid? _trackingUid;

    public MalfAiViewportWindow(MapId mapId, Vector2 worldPos, Vector2i sizePixels, string title, float rotation = 0f, int zoomLevel = 5, NetEntity? anchorEntity = null)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _eyeLerpingSystem = _entityManager.System<EyeLerpingSystem>();

        _anchorEntity = anchorEntity;
        Title = title;

        // Enforce a square internal viewport to guarantee 1:1 aspect ratio regardless of window size.
        var square = sizePixels.X > 0 && sizePixels.Y > 0 ? Math.Min(sizePixels.X, sizePixels.Y) : 400;
        var squareSize = new Vector2i(square, square);

        // Apply size hints to keep the window roughly to the requested size but ensure square viewport.
        MinWidth = square;
        MinHeight = square;
        Viewport.ViewportSize = squareSize;

        // Create fallback static eye first so viewport has something to render immediately
        CreateStaticEye(mapId, worldPos, rotation);

        // Try to bind to anchor immediately if it already exists
        UpdateAnchor();

        // Ensure we release the eye and lerping when window closes.
        OnClose += () =>
        {
            if (_trackingUid != null)
            {
                _eyeLerpingSystem.RemoveEye(_trackingUid.Value);
                _trackingUid = null;
            }
            Viewport.Eye = null;
            _staticEye = null;
        };

        OpenCentered();
    }

    private void UpdateAnchor()
    {
        if (_anchorEntity == null)
            return;

        var anchorUid = _entityManager.GetEntity(_anchorEntity.Value);
        if (!_entityManager.EntityExists(anchorUid))
            return;

        if (_trackingUid == anchorUid && Viewport.Eye != null && Viewport.Eye != _staticEye)
            return;

        if (_entityManager.TryGetComponent<EyeComponent>(anchorUid, out var eyeComp))
        {
            eyeComp.DrawFov = false;
            eyeComp.DrawLight = true;
            eyeComp.Zoom = new Vector2(DefaultZoom, DefaultZoom);
            _eyeLerpingSystem.AddEye(anchorUid, eyeComp);
            Viewport.Eye = eyeComp.Eye;
            _trackingUid = anchorUid;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_trackingUid == null)
        {
            if (_anchorEntity != null)
                UpdateAnchor();
        }
        else
        {
            // If the tracked entity was deleted or lost its eye component, fall back to static eye
            if (!_entityManager.EntityExists(_trackingUid.Value) || !_entityManager.HasComponent<EyeComponent>(_trackingUid.Value))
            {
                _eyeLerpingSystem.RemoveEye(_trackingUid.Value);
                _trackingUid = null;
                Viewport.Eye = _staticEye;
            }
        }
    }

    private void CreateStaticEye(MapId mapId, Vector2 worldPos, float rotation)
    {
        // Create and configure a dedicated eye centered on the requested world position.
        _staticEye = new FixedEye
        {
            // Draw lighting, disable humanoid cone FOV for Station AI
            DrawFov = false,
            DrawLight = true,
            Zoom = new Vector2(DefaultZoom, DefaultZoom),
            Rotation = -rotation
        };

        _staticEye.Position = new MapCoordinates(worldPos, mapId);

        // Assign eye to the viewport for rendering.
        Viewport.Eye = _staticEye;
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var baseSize = base.MeasureOverride(availableSize);

        // Clamp aspect ratio to prevent excessively wide or tall windows
        const float maxAspectRatio = 2.0f;

        var width = baseSize.X;
        var height = baseSize.Y;

        var aspectRatio = width / height;

        if (aspectRatio > maxAspectRatio)
        {
            width = height * maxAspectRatio;
        }
        else if (aspectRatio < 1.0f / maxAspectRatio)
        {
            height = width * maxAspectRatio;
        }

        return new Vector2(width, height);
    }
}
