using System;
using System.Collections.Generic;
using System.Linq;
using System.Numerics;
using Content.Client.MalfAI.Theme;
using Content.Shared.Roles;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.MalfAI.VoiceModulator;

[GenerateTypedNameReferences]
public sealed partial class MalfVoiceModulatorWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IResourceCache _resCache = default!;
    [Dependency] private readonly IEntitySystemManager _entSys = default!;

    private readonly SpriteSystem _spriteSystem;

    public event Action<bool, string, string?, string?>? OnUpdate;

    private bool _enabled;
    private string? _currentJobProtoId;
    private string? _currentAccent;

    // Job selection storage (HoP-style)
    // Index in OptionButton -> (jobProtoId, jobIconProtoId)
    private readonly List<(string? JobProtoId, ProtoId<JobIconPrototype> Icon)> _jobEntries = new();

    // Accent selection storage
    private readonly List<(string LocKey, string? CompName)> _accentEntries = new()
    {
        ("malf-voice-accent-none", null),
        ("malf-voice-accent-french", "FrenchAccent"),
        ("malf-voice-accent-german", "GermanAccent"),
        ("malf-voice-accent-russian", "RussianAccent"),
        ("malf-voice-accent-spanish", "SpanishAccent"),
        ("malf-voice-accent-southern", "SouthernAccent"),
        ("malf-voice-accent-pirate", "PirateAccent"),
        ("malf-voice-accent-mobster", "MobsterAccent"),
        ("malf-voice-accent-lizard", "LizardAccent"),
        ("malf-voice-accent-moth", "MothAccent"),
        ("malf-voice-accent-owo", "OwOAccent"),
        ("malf-voice-accent-skeleton", "SkeletonAccent"),
        ("malf-voice-accent-slurred", "SlurredAccent"),
        ("malf-voice-accent-stuttering", "StutteringAccent"),
        ("malf-voice-accent-frontallisp", "FrontalLisp"),
        ("malf-voice-accent-scrambled", "ScrambledAccent"),
    };

    private static readonly ProtoId<JobIconPrototype> DefaultAiJobIcon = "JobIconStationAi";

    public MalfVoiceModulatorWindow(Font? malfFont)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entSys.GetEntitySystem<SpriteSystem>();

        // Apply Malf theme backdrop & CRT static effects
        RootBackdrop.PanelOverride = MalfUiTheme.CreateBackdropStyle();
        var errorBackdrop = MalfEffectOverlay.CreateErrorBackdrop();
        RootBackdrop.AddChild(errorBackdrop);
        errorBackdrop.SetPositionInParent(0);
        var staticOverlay = MalfEffectOverlay.CreateStaticOverlay();
        RootBackdrop.AddChild(staticOverlay);

        // Apply Malf stylesheet
        RootBackdrop.Stylesheet = MalfUiTheme.GetCachedStylesheet(_resCache, 12);

        // Control styling
        StatusPanel.PanelOverride = MalfUiTheme.CreateCategoryPanelStyle();
        NameEdit.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(MalfUiTheme.Accent);
        JobOptionButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(MalfUiTheme.Accent);
        AccentOptionButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(MalfUiTheme.Accent);
        ClearNameButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(MalfUiTheme.Accent);
        ApplyButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(MalfUiTheme.Accent);
        DismissButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(Color.FromHex("#666666"));

        JobIconPreview.TextureScale = new Vector2(2f, 2f);

        // Localized labels
        Title = Loc.GetString("malf-voice-window-title");
        StatusHeaderLabel.Text = Loc.GetString("malf-voice-status-label");
        NameHeaderLabel.Text = Loc.GetString("malf-voice-name-label");
        NameEdit.PlaceHolder = Loc.GetString("malf-voice-name-placeholder");
        ClearNameButton.Text = Loc.GetString("malf-voice-clear-button");
        JobHeaderLabel.Text = Loc.GetString("malf-voice-job-label");
        AccentHeaderLabel.Text = Loc.GetString("malf-voice-accent-label");
        ApplyButton.Text = Loc.GetString("malf-voice-save-button");
        DismissButton.Text = Loc.GetString("malf-voice-close-button");

        // Populate options
        PopulateJobs();
        PopulateAccents();

        // Wire event handlers
        ToggleModulatorButton.OnPressed += _ =>
        {
            _enabled = !_enabled;
            UpdateToggleVisuals();
            NotifyUpdate();
        };

        JobOptionButton.OnItemSelected += args =>
        {
            JobOptionButton.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _jobEntries.Count)
            {
                var entry = _jobEntries[args.Id];
                _currentJobProtoId = entry.JobProtoId;
                UpdateJobPreview(entry.Icon);
            }
            NotifyUpdate();
        };

        AccentOptionButton.OnItemSelected += args =>
        {
            AccentOptionButton.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _accentEntries.Count)
            {
                _currentAccent = _accentEntries[args.Id].CompName;
            }
            NotifyUpdate();
        };

        ClearNameButton.OnPressed += _ =>
        {
            NameEdit.Text = string.Empty;
            NotifyUpdate();
        };

        NameEdit.OnTextEntered += _ => NotifyUpdate();
        NameEdit.OnFocusExit += _ => NotifyUpdate();

        ApplyButton.OnPressed += _ =>
        {
            NotifyUpdate();
            Close();
        };

        DismissButton.OnPressed += _ => Close();

        UpdateToggleVisuals();
        UpdateJobPreview(DefaultAiJobIcon);
    }

    private void PopulateJobs()
    {
        JobOptionButton.Clear();
        _jobEntries.Clear();

        // Option 0: Default Station AI
        JobOptionButton.AddItem(Loc.GetString("malf-voice-job-default"), 0);
        _jobEntries.Add((null, DefaultAiJobIcon));

        // Reusing HoP job listing: Enumerate JobPrototype, filter by OverrideConsoleVisibility/SetPreference, sort by LocalizedName
        var jobs = _proto.EnumeratePrototypes<JobPrototype>().ToList();
        jobs.Sort((x, y) => string.Compare(x.LocalizedName, y.LocalizedName, StringComparison.CurrentCulture));

        var index = 1;
        foreach (var job in jobs)
        {
            if (!job.OverrideConsoleVisibility.GetValueOrDefault(job.SetPreference))
                continue;

            _jobEntries.Add((job.ID, job.Icon));
            JobOptionButton.AddItem(job.LocalizedName, index);
            index++;
        }
    }

    private void PopulateAccents()
    {
        AccentOptionButton.Clear();
        for (var i = 0; i < _accentEntries.Count; i++)
        {
            AccentOptionButton.AddItem(Loc.GetString(_accentEntries[i].LocKey), i);
        }
    }

    public void SetState(bool enabled, string name, string? jobProtoId, string? accent)
    {
        _enabled = enabled;
        _currentJobProtoId = jobProtoId;
        _currentAccent = accent;

        NameEdit.Text = name;

        // Select Job
        var jobIndex = 0;
        if (!string.IsNullOrEmpty(jobProtoId))
        {
            var found = _jobEntries.FindIndex(j => j.JobProtoId == jobProtoId);
            if (found >= 0)
                jobIndex = found;
        }
        JobOptionButton.SelectId(jobIndex);
        UpdateJobPreview(_jobEntries[jobIndex].Icon);

        // Select Accent
        var accentIndex = 0;
        if (!string.IsNullOrEmpty(accent))
        {
            var found = _accentEntries.FindIndex(a => a.CompName == accent);
            if (found >= 0)
                accentIndex = found;
        }
        AccentOptionButton.SelectId(accentIndex);

        UpdateToggleVisuals();
    }

    private void UpdateToggleVisuals()
    {
        if (_enabled)
        {
            ToggleModulatorButton.Text = Loc.GetString("malf-voice-status-enabled");
            ToggleModulatorButton.Modulate = Color.FromHex("#33FF33");
            ToggleModulatorButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(Color.FromHex("#00FF66"));
            StatusLabel.Text = Loc.GetString("malf-voice-status-active-desc");
            StatusLabel.FontColorOverride = Color.FromHex("#33FF33");
        }
        else
        {
            ToggleModulatorButton.Text = Loc.GetString("malf-voice-status-disabled");
            ToggleModulatorButton.Modulate = Color.FromHex("#FF5555");
            ToggleModulatorButton.StyleBoxOverride = MalfUiTheme.CreateButtonStyle(Color.FromHex("#884444"));
            StatusLabel.Text = Loc.GetString("malf-voice-status-inactive-desc");
            StatusLabel.FontColorOverride = Color.FromHex("#AAAAAA");
        }
    }

    private void UpdateJobPreview(ProtoId<JobIconPrototype> iconProtoId)
    {
        if (_proto.TryIndex(iconProtoId, out var jobIcon))
        {
            JobIconPreview.Texture = _spriteSystem.Frame0(jobIcon.Icon);
        }
        else
        {
            JobIconPreview.Texture = null;
        }
    }

    private void NotifyUpdate()
    {
        var name = NameEdit.Text?.Trim() ?? string.Empty;
        OnUpdate?.Invoke(_enabled, name, _currentJobProtoId, _currentAccent);
    }
}
