        const float step = 18f;

        switch (_currentApp)
        {
            case PagerApp.Launcher:
                _launcherScrollOffset = MathF.Max(0, _launcherScrollOffset + direction * step);
                LauncherScroll.SetScrollValue(new Vector2(0, _launcherScrollOffset));
                break;
            case PagerApp.Chat:
                _chatScrollOffset = MathF.Max(0, _chatScrollOffset + direction * step);
                ChatScroll.SetScrollValue(new Vector2(0, _chatScrollOffset));
                break;
            case PagerApp.Calls:
                _callScrollOffset = MathF.Max(0, _callScrollOffset + direction * step);
                CallScroll.SetScrollValue(new Vector2(0, _callScrollOffset));
                break;
            case PagerApp.Manifest:
                _manifestScrollOffset = MathF.Max(0, _manifestScrollOffset + direction * step);
                ManifestScroll.SetScrollValue(new Vector2(0, _manifestScrollOffset));
                break;
            case PagerApp.Diagnostics:
                _sysScrollOffset = MathF.Max(0, _sysScrollOffset + direction * step);
                SysScroll.SetScrollValue(new Vector2(0, _sysScrollOffset));
                break;
            case PagerApp.Store:
                _storeScrollOffset = MathF.Max(0, _storeScrollOffset + direction * step);
                StoreScroll.SetScrollValue(new Vector2(0, _storeScrollOffset));
                break;
            case PagerApp.Notes:
                _notesScrollOffset = MathF.Max(0, _notesScrollOffset + direction * step);
                NotesScroll.SetScrollValue(new Vector2(0, _notesScrollOffset));
                break;
            case PagerApp.News:
                _newsScrollOffset = MathF.Max(0, _newsScrollOffset + direction * step);
                NewsScroll.SetScrollValue(new Vector2(0, _newsScrollOffset));
                break;
            case PagerApp.Bank:
                _bankScrollOffset = MathF.Max(0, _bankScrollOffset + direction * step);
                BankScroll.SetScrollValue(new Vector2(0, _bankScrollOffset));
                break;
            case PagerApp.Database:
                _dbScrollOffset = MathF.Max(0, _dbScrollOffset + direction * step);
                DbScroll.SetScrollValue(new Vector2(0, _dbScrollOffset));
                break;
            case PagerApp.Shields:
                _shieldsScrollOffset = MathF.Max(0, _shieldsScrollOffset + direction * step);
                ShieldsScroll.SetScrollValue(new Vector2(0, _shieldsScrollOffset));
