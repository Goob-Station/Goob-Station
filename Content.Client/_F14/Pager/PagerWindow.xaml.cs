    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_currentApp != PagerApp.Snake || _snakeGameOver || !_snakeStarted)
            return;

        _snakeTickAccumulator += args.DeltaSeconds;
        if (_snakeTickAccumulator < SnakeTickInterval)
            return;

        _snakeTickAccumulator = 0f;
        SnakeTick();
    }

    private static string BuildUsageBar(int used, int total, int length = 10)
    {
        if (total <= 0)
            return new string('.', length);

        var filled = Math.Clamp((int) MathF.Round(length * (used / (float) total)), 0, length);
        return new string('#', filled) + new string('.', length - filled);
    }

    private void ResetSnake()
    {
        _snakeBody = new List<Vector2i>
        {
            new(8, 4),
            new(7, 4),
            new(6, 4)
        };
        _snakeDir = SnakeDir.Right;
        _snakeNextDir = SnakeDir.Right;
        _snakeScore = 0;
        _snakeGameOver = false;
        _snakeStarted = true;
        _snakeTickAccumulator = 0f;
        SpawnSnakeFood();
        SnakeStatusLabel.Text = "SNAKE.EXE | SCORE: 0";
        RenderSnake();
    }

    private void SpawnSnakeFood()
    {
        Vector2i pos;
        do
        {
            pos = new Vector2i(_random.Next(0, SnakeCols), _random.Next(0, SnakeRows));
        } while (_snakeBody.Contains(pos));

        _snakeFood = pos;
    }

    private void SnakeTick()
    {
        _snakeDir = _snakeNextDir;
        var head = _snakeBody[0];

        var delta = _snakeDir switch
        {
            SnakeDir.Up => new Vector2i(0, -1),
            SnakeDir.Down => new Vector2i(0, 1),
            SnakeDir.Left => new Vector2i(-1, 0),
            SnakeDir.Right => new Vector2i(1, 0),
            _ => new Vector2i(0, 0)
        };

        var newHead = new Vector2i(head.X + delta.X, head.Y + delta.Y);

        if (newHead.X < 0 || newHead.X >= SnakeCols ||
            newHead.Y < 0 || newHead.Y >= SnakeRows ||
            _snakeBody.Contains(newHead))
        {
            _snakeGameOver = true;
            SnakeStatusLabel.Text = $"SNAKE.EXE | GAME OVER (SCORE: {_snakeScore})";
            return;
        }

        _snakeBody.Insert(0, newHead);

        if (newHead == _snakeFood)
        {
            _snakeScore++;
            SnakeStatusLabel.Text = $"SNAKE.EXE | SCORE: {_snakeScore}";
            SpawnSnakeFood();
        }
        else
        {
            _snakeBody.RemoveAt(_snakeBody.Count - 1);
        }

        RenderSnake();
    }

    private void BuildSnakeGrid()
    {
        if (_snakeCells != null)
            return;

        _snakeCells = new PanelContainer[SnakeCols, SnakeRows];

        for (var x = 0; x < SnakeCols; x++)
        for (var y = 0; y < SnakeRows; y++)
        {
            var cell = new PanelContainer
            {
                PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#00000000") }
            };
            LayoutContainer.SetPosition(cell, new Vector2(x * SnakeCellSize, y * SnakeCellSize));
            cell.SetSize = new Vector2(SnakeCellSize - 1, SnakeCellSize - 1);
            SnakeCanvas.AddChild(cell);
            _snakeCells[x, y] = cell;
        }
    }

    private void RenderSnake()
    {
        BuildSnakeGrid();

        for (var x = 0; x < SnakeCols; x++)
        for (var y = 0; y < SnakeRows; y++)
            _snakeCells![x, y].PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#00000000") };

        foreach (var seg in _snakeBody)
        {
            if (seg.X < 0 || seg.X >= SnakeCols || seg.Y < 0 || seg.Y >= SnakeRows)
                continue;
            _snakeCells![seg.X, seg.Y].PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#152812") };
        }

        _snakeCells![_snakeFood.X, _snakeFood.Y].PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#8c4444") };
    }

    private void AddCurrentNote()
    {
        if (string.IsNullOrWhiteSpace(NoteInput.Text))
            return;

