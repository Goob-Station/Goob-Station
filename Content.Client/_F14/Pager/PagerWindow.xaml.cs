    private void BuildAppLauncher(PagerBoundUserInterfaceState state)
    {
        AppGrid.DisposeAllChildren();

        foreach (var id in state.InstalledSoftware)
        {
            if (id == "scpos_id_modification" ||
                id.Contains("id_modification", StringComparison.OrdinalIgnoreCase) ||
                id.Contains("library", StringComparison.OrdinalIgnoreCase) ||
                id.Contains("report", StringComparison.OrdinalIgnoreCase) ||
                id.Contains("p2p", StringComparison.OrdinalIgnoreCase) ||
                id.Contains("email", StringComparison.OrdinalIgnoreCase) ||
                id.Contains("relay_chat_server", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var appTitle = GetAppDisplayName(id);
            if (_proto.TryIndex<SCPOSSoftwarePrototype>(id, out var proto))
                appTitle = proto.Name;

            string? iconPath = id switch
            {
                "scpos_relay_chat_client" => "/Textures/_F14/Interface/Pager/Icons/chat.png",
                "scpos_dispatch" => "/Textures/_F14/Interface/Pager/Icons/call.png",
                "scpos_personnel_manifest" => "/Textures/_F14/Interface/Pager/Icons/manifest.png",
                "scpos_taxquickly" => "/Textures/_F14/Interface/Pager/Icons/tax.png",
                "scpos_micro_arcade" => "/Textures/_F14/Interface/Pager/Icons/arcade.png",
                "scpos_scanner" => "/Textures/_F14/Interface/Pager/Icons/scanner.png",
                "scpos_database_client" => "/Textures/_F14/Interface/Pager/Icons/briefcase.png",
                "scpos_crew_records" => "/Textures/_F14/Interface/Pager/Icons/briefcase.png",
                "scpos_supply_management" => "/Textures/_F14/Interface/Pager/Icons/briefcase.png",
                "scpos_nanoword" => "/Textures/_F14/Interface/Pager/Icons/briefcase.png",
                _ => "/Textures/_F14/Interface/Pager/Icons/briefcase.png"
            };

            if (proto != null && !string.IsNullOrEmpty(proto.Icon) && _resCache.ContentFileExists(new ResPath(proto.Icon)))
                iconPath = proto.Icon;

            var appId = id;
            AppGrid.AddChild(CreateAppButton(appTitle, iconPath, () =>
            {
                if (appId == "scpos_relay_chat_client" || appId.Contains("chat", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Chat);
                else if (appId == "scpos_dispatch" || appId.Contains("dispatch", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Calls);
                else if (appId == "scpos_personnel_manifest" || appId.Contains("manifest", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Manifest);
                else if (appId == "scpos_nanoword" || appId.Contains("notes", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Notes);
                else if (appId == "scpos_taxquickly" || appId.Contains("bank", StringComparison.OrdinalIgnoreCase) || appId.Contains("tax", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Bank);
                else if (appId == "scpos_database_client" || appId.Contains("database", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Database);
                else if (appId == "scpos_shield_generators" || appId.Contains("shield", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Shields);
                else if (appId == "scpos_crew_records" || appId.Contains("records", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Records);
                else if (appId == "scpos_supply_management" || appId.Contains("supply", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Supply);
                else if (appId == "scpos_scanner" || appId.Contains("scanner", StringComparison.OrdinalIgnoreCase))
                    SwitchProgram(PagerApp.Scanner);
            }));
        }

        AppGrid.AddChild(CreateAppButton("System", "/Textures/_F14/Interface/Pager/Icons/settings.png", () => SwitchProgram(PagerApp.Diagnostics)));
        AppGrid.AddChild(CreateAppButton("Store", "/Textures/_F14/Interface/Pager/Icons/briefcase.png", () => SwitchProgram(PagerApp.Store)));
        AppGrid.AddChild(CreateAppButton("Snake", "/Textures/_F14/Interface/Pager/Icons/snake.png", () => SwitchProgram(PagerApp.Snake)));
    }

    private Button CreateAppButton(string title, string? iconPath, Action onClick)
    {
        var btn = new Button
        {
            Modulate = Color.FromHex("#526c48"),
            HorizontalExpand = true,
            Margin = new Thickness(1, 1),
            MinHeight = 24,
            MaxHeight = 24,
            MinWidth = 168,
            MaxWidth = 168
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(4, 1),
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true
        };

        if (!string.IsNullOrEmpty(iconPath) && _resCache.ContentFileExists(new ResPath(iconPath)))
        {
            box.AddChild(new TextureRect
            {
                TexturePath = iconPath,
                SetSize = new Vector2(16, 16),
                MinSize = new Vector2(16, 16),
                Stretch = TextureRect.StretchMode.KeepCentered,
                Margin = new Thickness(0, 0, 4, 0),
                VerticalAlignment = VAlignment.Center
            });
        }
        else
        {
            box.AddChild(new Label
            {
                Text = "> ",
                FontColorOverride = _lcdTextColor,
                VerticalAlignment = VAlignment.Center
            });
        }

        var lbl = new Label
        {
            Text = title,
            FontColorOverride = _lcdTextColor,
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
            ClipText = true
        };
        if (_chatFont != null)
            lbl.FontOverride = _chatFont;

        box.AddChild(lbl);
        btn.AddChild(box);
        btn.OnPressed += _ => onClick();
        return btn;
    }

    private void BuildStoreList(PagerBoundUserInterfaceState state)
    {
        DiskUsageLabel.Text = $"MEM: {state.DiskUsed}/{state.DiskCapacity}GQ";

        if (state.InsertedIdName is null)
        {
            IdStatusLabel.Text = "NO ID";
            EjectIdBtn.Disabled = true;
        }
        else
        {
            IdStatusLabel.Text = $"ID: {state.InsertedIdName.ToUpper()}";
            EjectIdBtn.Disabled = false;
        }

        StoreListContainer.DisposeAllChildren();

        var allSoftware = _proto.EnumeratePrototypes<SCPOSSoftwarePrototype>()
            .OrderBy(s => s.Core ? 0 : 1)
            .ThenBy(s => s.Name);

        foreach (var software in allSoftware)
        {
            if (software.ID.Contains("arcade", StringComparison.OrdinalIgnoreCase) ||
                software.ID.Contains("library", StringComparison.OrdinalIgnoreCase) ||
                software.ID.Contains("report", StringComparison.OrdinalIgnoreCase) ||
                software.ID.Contains("p2p", StringComparison.OrdinalIgnoreCase) ||
                software.ID.Contains("email", StringComparison.OrdinalIgnoreCase) ||
                software.ID.Contains("relay_chat_server", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var hasAccess = software.RequiredAccess.Count == 0
                || software.RequiredAccess.Any(t => state.CurrentAccessTags.Contains(t));

            if (!hasAccess)
                continue;

            StoreListContainer.AddChild(BuildStoreEntry(software, state));
        }
    }

    private Control BuildStoreEntry(SCPOSSoftwarePrototype software, PagerBoundUserInterfaceState state)
    {
        var installed = state.InstalledSoftware.Contains(software.ID);
        var fitsOnDisk = state.DiskUsed + software.DiskCost <= state.DiskCapacity;

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 1)
        };

        row.AddChild(new Label
        {
            Text = software.Name,
            FontColorOverride = _lcdTextColor,
            HorizontalExpand = true
        });

        row.AddChild(new Label
        {
            Text = $"{software.DiskCost}GQ",
            FontColorOverride = _lcdTextColor,
            Margin = new Thickness(0, 0, 4, 0)
        });

        if (software.Core)
        {
            row.AddChild(new Label { Text = "[CORE]", FontColorOverride = _lcdTextColor });
        }
        else if (installed)
        {
            var delBtn = new Button { Modulate = Color.FromHex("#708c62"), MinHeight = 16 };
            delBtn.AddChild(new Label { Text = "DEL", FontColorOverride = _lcdTextColor, Margin = new Thickness(3, 0) });
            var id = software.ID;
            delBtn.OnPressed += _ => OnSoftwareUninstallRequested?.Invoke(id);
            row.AddChild(delBtn);
        }
        else if (!fitsOnDisk)
        {
            row.AddChild(new Label { Text = "[NO MEM]", FontColorOverride = Color.FromHex("#8c4444") });
        }
        else
        {
            var dlBtn = new Button { Modulate = Color.FromHex("#526c48"), MinHeight = 16 };
            dlBtn.AddChild(new Label { Text = "GET", FontColorOverride = _lcdTextColor, Margin = new Thickness(3, 0) });
            var id = software.ID;
            dlBtn.OnPressed += _ => OnSoftwareDownloadRequested?.Invoke(id);
            row.AddChild(dlBtn);
        }

        return row;
    }
