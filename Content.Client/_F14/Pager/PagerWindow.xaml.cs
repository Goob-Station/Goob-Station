        NoteInput.Text = string.Empty;
        ToggleKeyboard(false);
    }

    private void HandleUpAction()
    {
        if (_currentApp == PagerApp.Chat && RecipientMenuArea.Visible)
        {
            _recipientMenuIndex = Math.Max(0, _recipientMenuIndex - 1);
            RenderRecipientMenu();
            return;
        }

        ScrollOrCycle(-1);
    }

    private void HandleDownAction()
    {
        if (_currentApp == PagerApp.Chat && RecipientMenuArea.Visible)
        {
            _recipientMenuIndex = Math.Min(_recipientOptions.Count - 1, _recipientMenuIndex + 1);
            RenderRecipientMenu();
            return;
        }

        ScrollOrCycle(1);
    }

    private void ScrollOrCycle(int direction)
