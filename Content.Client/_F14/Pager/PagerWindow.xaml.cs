    private void ToggleRecipientMenu(bool open)
    {
        RecipientMenuArea.Visible = open;
        ChatMainArea.Visible = !open;

        if (open)
        {
            BuildRecipientOptionsList();
            RenderRecipientMenu();
        }
    }

    private void BuildRecipientOptionsList()
    {
        _recipientOptions.Clear();
        _recipientOptions.Add(null);
        foreach (var name in _availableRecipients)
        {
            _recipientOptions.Add(name);
        }

        var currentIndex = _recipientOptions.IndexOf(_selectedRecipient);
        _recipientMenuIndex = currentIndex >= 0 ? currentIndex : 0;
    }

    private void RenderRecipientMenu()
    {
        RecipientListContainer.DisposeAllChildren();

        for (var i = 0; i < _recipientOptions.Count; i++)
        {
            var opt = _recipientOptions[i];
            var isSelected = i == _recipientMenuIndex;
            var prefix = isSelected ? "> " : "  ";
            var text = opt == null ? "[BROADCAST (ALL)]" : opt;

            var btn = new Button
            {
                Modulate = isSelected ? Color.FromHex("#708c62") : Color.FromHex("#526c48"),
                HorizontalExpand = true,
                Margin = new Thickness(0, 1),
                MinHeight = 16
            };

            var label = new Label
            {
                Text = $"{prefix}{text}",
                FontColorOverride = _lcdTextColor,
                Margin = new Thickness(3, 1)
            };
            if (_chatFont != null)
                label.FontOverride = _chatFont;

            btn.AddChild(label);

            var idx = i;
            btn.OnPressed += _ =>
            {
                _recipientMenuIndex = idx;
                SelectHighlightedRecipient();
            };

            RecipientListContainer.AddChild(btn);
        }

        RecipientScroll.SetScrollValue(new Vector2(0, _recipientMenuIndex * 18));
    }

    private void SelectHighlightedRecipient()
    {
        if (_recipientMenuIndex >= 0 && _recipientMenuIndex < _recipientOptions.Count)
        {
            _selectedRecipient = _recipientOptions[_recipientMenuIndex];
            RecipientLabel.Text = _selectedRecipient == null
                ? "[BROADCAST (ALL)]"
                : $"[PM: {_selectedRecipient}]";
        }

        ToggleRecipientMenu(false);
    }

    public void SetDirectMessageRecipient(string recipient)
    {
        _selectedRecipient = recipient;
        RecipientLabel.Text = $"[PM: {_selectedRecipient}]";
        SwitchProgram(PagerApp.Chat);
        ToggleRecipientMenu(false);
        ToggleKeyboard(true);
    }

    private void SendCurrentMessage()
    {
        if (string.IsNullOrWhiteSpace(LcdInputMsg.Text))
            return;

        OnMessageSent?.Invoke(_selectedRecipient, LcdInputMsg.Text);
        LcdInputMsg.Text = string.Empty;
        ToggleKeyboard(false);
    }

    public void ToggleKeyboard(bool open)
    {
        KeyboardPanel.Visible = open;
        SetSize = open ? new Vector2(500, 435) : new Vector2(500, 325);

        if (open)
        {
            if (_currentApp == PagerApp.Chat && !RecipientMenuArea.Visible)
                LcdInputMsg.GrabKeyboardFocus();
            else if (_currentApp == PagerApp.Notes)
                NoteInput.GrabKeyboardFocus();
            else if (_currentApp == PagerApp.IdEdit)
                IdNameInput.GrabKeyboardFocus();
        }
    }

