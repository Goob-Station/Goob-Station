    public void UpdateState(PagerBoundUserInterfaceState state)
    {
        CallStatusLabel.Text = state.CallState switch
        {
            PagerCallState.InCall => $"CALL ACTIVE: {state.CallPartnerName}",
            PagerCallState.IncomingRinging => $"INCOMING: {state.CallPartnerName}",
            PagerCallState.OutgoingRinging => $"CALLING {state.CallPartnerName}...",
            _ => "CALL STATUS: STANDBY"
        };

        InfoOwnerLabel.Text = $"OPERATOR: {state.OwnerName.ToUpper()}";

        StorageLabel.Text = $"STORAGE: {state.DiskCapacity} GQ FLASH";
        UsageLabel.Text = $"USAGE: [{BuildUsageBar(state.DiskUsed, state.DiskCapacity)}] {state.DiskUsed}/{state.DiskCapacity} GQ";
        EarpieceLabel.Text = state.EarpieceLinked
            ? "EARPIECE: LINK ACTIVE (SLOT: EARS)"
            : "EARPIECE: NOT DETECTED";

        IdEditStatusLabel.Text = state.InsertedIdName is null
            ? "NO ID INSERTED"
            : $"CURRENT: {state.InsertedIdName.ToUpper()}";
        IdSaveBtn.Disabled = state.InsertedIdName is null;

        _availableRecipients.Clear();
        ContactsContainer.DisposeAllChildren();
        if (state.AvailableContacts.Count == 0)
        {
            ContactsContainer.AddChild(new Label { Text = "No pagers on network.", FontColorOverride = _lcdTextColor });
        }
        else
        {
            foreach (var (netUid, name) in state.AvailableContacts)
            {
                _availableRecipients.Add(name);

                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                row.AddChild(new Label { Text = name, FontColorOverride = _lcdTextColor, HorizontalExpand = true });

                var msgBtn = new Button { Modulate = Color.FromHex("#526c48"), Margin = new Thickness(0, 0, 2, 0) };
                msgBtn.AddChild(new Label { Text = "MSG", FontColorOverride = _lcdTextColor, Margin = new Thickness(3, 0) });
                var targetName = name;
                msgBtn.OnPressed += _ => SetDirectMessageRecipient(targetName);
                row.AddChild(msgBtn);

                var callBtn = new Button { Modulate = Color.FromHex("#526c48") };
                callBtn.AddChild(new Label { Text = "CALL", FontColorOverride = _lcdTextColor, Margin = new Thickness(3, 0) });
                var target = netUid;
                callBtn.OnPressed += _ => OnCallRequested?.Invoke(target);
                row.AddChild(callBtn);

                ContactsContainer.AddChild(row);
            }
        }

        ManifestContainer.DisposeAllChildren();
        foreach (var entry in state.Manifest)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new Label { Text = $"- {entry.Name}", FontColorOverride = _lcdTextColor, HorizontalExpand = true });
            row.AddChild(new Label { Text = $" [{entry.JobTitle}]", FontColorOverride = _lcdTextColor });
            ManifestContainer.AddChild(row);
        }

        ChatContainer.DisposeAllChildren();
        foreach (var msg in state.Messages)
        {
            var isPm = !string.IsNullOrEmpty(msg.Recipient);
            var tag = isPm ? $"[PM->{msg.Recipient}]" : "[ALL]";
            var lbl = new Label
            {
                Text = $"{tag} {msg.Sender}: {msg.Text}",
                FontColorOverride = _lcdTextColor,
                Margin = new Thickness(0, 1)
            };
            if (_chatFont != null)
                lbl.FontOverride = _chatFont;

            ChatContainer.AddChild(lbl);
        }
        _chatScrollOffset = 50000f;
        ChatScroll.SetScrollValue(new Vector2(0, _chatScrollOffset));

        NotesListContainer.DisposeAllChildren();
        for (var i = 0; i < state.Notes.Count; i++)
        {
            var noteRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1) };
            var noteLbl = new Label { Text = $"* {state.Notes[i]}", FontColorOverride = _lcdTextColor, HorizontalExpand = true };
