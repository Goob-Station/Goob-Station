using Content.Shared.CCVar; // Goob
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration; // Goob
using Robust.Shared.Utility;

namespace Content.Client.FlavorText
{
    [GenerateTypedNameReferences]
    public sealed partial class FlavorText : Control
    {
        public Action<string>? OnFlavorTextChanged;

        public FlavorText()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            var loc = IoCManager.Resolve<ILocalizationManager>();
            CFlavorTextInput.Placeholder = new Rope.Leaf(loc.GetString("flavor-text-placeholder"));
            CFlavorTextInput.OnTextChanged  += _ => FlavorTextChanged();
        }

        public void FlavorTextChanged()
        {
            OnFlavorTextChanged?.Invoke(Rope.Collapse(CFlavorTextInput.TextRope).Trim());
            UpdatePreview(); // Goob
        }

        // Goob start
        public void UpdatePreview()
        {
            var text = Rope.Collapse(CFlavorTextInput.TextRope).Trim();
            var max = IoCManager.Resolve<IConfigurationManager>().GetCVar(CCVars.MaxFlavorTextLength);
            CFlavorTextCount.Text = Loc.GetString("flavor-text-count", ("count", text.Length), ("max", max));
            CFlavorTextCount.FontColorOverride = text.Length > max ? Color.FromHex("#d65c5c") : null;
            CFlavorTextPreview.SetMessage(text.Length == 0
                ? FormattedMessage.FromUnformatted(Loc.GetString("flavor-text-examine-empty"))
                : FormattedMessage.FromMarkupPermissive(text));
        }
        // Goob end
    }
}