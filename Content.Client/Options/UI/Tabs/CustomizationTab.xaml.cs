[GenerateTypedNameReferences]
public sealed partial class CustomizationTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private (bool Enabled, int FontSize, float Outline)? _previewState;

    public CustomizationTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Control.AddOptionCheckBox(GoobCVars.ChatRunechat, RunechatCheckBox);
        Control.AddOptionSlider(GoobCVars.ChatRunechatFontSize, RunechatFontSizeSlider, RunechatStyle.MinFontSize, RunechatStyle.MaxFontSize);
        Control.AddOptionPercentSlider(GoobCVars.ChatRunechatOutlineScale, RunechatOutlineSlider, 0f, 2f);
        RunechatPreviewPanel.PanelOverride = new StyleBoxFlat(Color.FromHex("#3b3e45"));
        Control.AddOptionCheckBox(CCVars.ChatEnableFancyBubbles, FancySpeechBubblesCheckBox);
        Control.AddOptionCheckBox(CCVars.ChatFancyNameBackground, FancyNameBackgroundsCheckBox);

        Control.AddOptionColorSlider(CCVars.ChatHighlightsColor, HighlightsColorSlider);

        Control.AddOptionCheckBox(GoobCVars.UseCustomRadioChannelColors, UseCustomRadioChannelColors);
        Control.AddOption(new OptionRadioChannelColors(Control, _cfg, _prototype, RadioChannelColorsContainer));

        Control.AddOptionCheckBox(GoobCVars.UseCustomInteractionOutlineColors, UseCustomInteractionOutlineColors);
        Control.AddOptionColorSlider(GoobCVars.ValidInteractionOutlineColor, ValidInteractionOutlineColorSlider);
        Control.AddOptionColorSlider(GoobCVars.InvalidInteractionOutlineColor, InvalidInteractionOutlineColorSlider);

        Control.Initialize();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var state = (RunechatCheckBox.Pressed,
            (int) MathF.Round(RunechatFontSizeSlider.Slider.Value),
            RunechatOutlineSlider.Slider.Value);

        if (_previewState == state)
            return;

        _previewState = state;
        UpdateRunechatPreview(state.Item1, state.Item2, state.Item3);
    }

    private void UpdateRunechatPreview(bool enabled, int fontSize, float outline)
    {
        RunechatPreview.RemoveAllChildren();

        if (enabled)
        {
            var nameColor = RunechatSpeechBubble.GetNameColor("John Doe");
            AddRunechatPreviewRow("normal", nameColor, false, false, fontSize, outline);
            AddRunechatPreviewRow("loud", nameColor, false, true, fontSize, outline);
            AddRunechatPreviewRow("whisper", nameColor, true, false, fontSize, outline);
            AddRunechatPreviewRow("emote", nameColor, false, false, fontSize, outline);
            AddRunechatPreviewRow("looc", RunechatSpeechBubble.LoocColor, false, false, fontSize, outline);
        }

        AddPopupPreviewRow("small", PopupType.Small, enabled, fontSize, outline);
        AddPopupPreviewRow("medium", PopupType.MediumCaution, enabled, fontSize, outline);
        AddPopupPreviewRow("large", PopupType.LargeCaution, enabled, fontSize, outline);
    }

    private void AddRunechatPreviewRow(string key, Color color, bool whisper, bool loud, int fontSize, float outline)
    {
        var text = Loc.GetString($"ui-options-runechat-preview-{key}-text");
        AddPreviewRow(key, RunechatSpeechBubble.CreateLabel(text, color, whisper, loud, fontSize, outline));
    }

    private void AddPopupPreviewRow(string key, PopupType type, bool runechat, int fontSize, float outline)
    {
        var (font, color, thickness) = PopupUIController.GetPopupStyle(type, runechat, fontSize, outline);
        var label = new Label
        {
            Text = Loc.GetString($"ui-options-runechat-preview-popup-{key}-text"),
            FontOverride = font,
            FontColorOverride = color,
            OutlineThicknessOverride = thickness,
            OutlineColorOverride = Color.Black,
            Margin = new Thickness(MathF.Ceiling(thickness)),
        };
        AddPreviewRow($"popup-{key}", label);
    }

    private void AddPreviewRow(string key, Control sample)
    {
        sample.VerticalAlignment = VAlignment.Center;
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        row.AddChild(new Label
        {
            Text = Loc.GetString($"ui-options-runechat-preview-{key}"),
            MinWidth = 160,
            VerticalAlignment = VAlignment.Center,
        });
        row.AddChild(sample);
        RunechatPreview.AddChild(row);
    }
}

/// <summary>
/// One color slider per radio channel, stored together in <see cref="GoobCVars.RadioChannelColors"/>.
/// Only channels whose color differs from the channel's own color are saved.
/// </summary>
public sealed class OptionRadioChannelColors : BaseOption
{
    private readonly IConfigurationManager _cfg;
    private readonly List<(RadioChannelPrototype Channel, OptionColorSlider Slider)> _sliders = new();

    public OptionRadioChannelColors(
        OptionsTabControlRow controller,
        IConfigurationManager cfg,
        IPrototypeManager prototype,
        BoxContainer container) : base(controller)
    {
        _cfg = cfg;

        foreach (var channel in prototype.EnumeratePrototypes<RadioChannelPrototype>().OrderBy(c => c.LocalizedName))
        {
            var slider = new OptionColorSlider
            {
                Title = channel.LocalizedName,
                Example = Loc.GetString("ui-options-radio-channel-colors-example", ("channel", channel.LocalizedName)),
            };

            slider.Slider.OnColorChanged += _ =>
            {
                UpdateExample(slider);
                ValueChanged();
            };

            var captured = channel;
            slider.ResetDefaults.OnPressed += _ =>
            {
                SetSlider(slider, captured.Color);
                ValueChanged();
            };

            container.AddChild(slider);
            _sliders.Add((channel, slider));
        }
    }

    public override void LoadValue()
    {
        var overrides = RadioChannelColorSystem.Parse(_cfg.GetCVar(GoobCVars.RadioChannelColors));
        foreach (var (channel, slider) in _sliders)
        {
            SetSlider(slider, overrides.GetValueOrDefault(channel.ID, channel.Color));
        }
    }

    public override void SaveValue()
    {
        _cfg.SetCVar(GoobCVars.RadioChannelColors, GetUiValue());
    }

    public override void ResetToDefault()
    {
        foreach (var (channel, slider) in _sliders)
        {
            SetSlider(slider, channel.Color);
        }
    }

    public override bool IsModified()
    {
        return GetUiValue() != Normalize(_cfg.GetCVar(GoobCVars.RadioChannelColors));
    }

    public override bool IsModifiedFromDefault()
    {
        return GetUiValue() != string.Empty;
    }

    private string GetUiValue()
    {
        var changed = new List<KeyValuePair<string, Color>>();
        foreach (var (channel, slider) in _sliders)
        {
            var color = slider.Slider.Color;
            if (color.ToHex() != channel.Color.ToHex())
                changed.Add(new KeyValuePair<string, Color>(channel.ID, color));
        }

        return RadioChannelColorSystem.Serialize(changed);
    }

    private string Normalize(string value)
    {
        var overrides = RadioChannelColorSystem.Parse(value);
        var changed = new List<KeyValuePair<string, Color>>();
        foreach (var (channel, _) in _sliders)
        {
            if (overrides.TryGetValue(channel.ID, out var color) && color.ToHex() != channel.Color.ToHex())
                changed.Add(new KeyValuePair<string, Color>(channel.ID, color));
        }

        return RadioChannelColorSystem.Serialize(changed);
    }

    private static void SetSlider(OptionColorSlider slider, Color color)
    {
        slider.Slider.Color = color;
        UpdateExample(slider);
    }

    private static void UpdateExample(OptionColorSlider slider)
    {
        slider.ExampleLabel.FontColorOverride = slider.Slider.Color.WithAlpha(1f);
    }
}
